create table tab.aql_scheme (
  code            text not null check (code ~ '^[A-Z][A-Z-]{1,39}$'),
  version         text not null check (version ~ '^[1-9][0-9]{0,3}$'),
  source          text not null check (btrim(source) <> ''),
  effective_from  date not null,
  confidence      text not null check (confidence in ('HIGH', 'MEDIUM', 'LOW')),
  recorded_at     timestamptz not null default clock_timestamp(),
  primary key (code, version)
);

create table tab.aql_letter (
  code         text not null,
  version      text not null,
  letter       text not null check (letter ~ '^[A-Z]$'),
  position     integer not null check (position >= 0),
  sample_size  bigint not null check (sample_size > 0),
  primary key (code, version, letter),
  unique (code, version, position),
  foreign key (code, version) references tab.aql_scheme (code, version)
);

create table tab.aql_sample_code (
  code      text not null,
  version   text not null,
  lot_from  bigint not null check (lot_from >= 1),
  lot_to    bigint check (lot_to is null or lot_to >= lot_from),
  level_i   text not null,
  level_ii  text not null,
  level_iii text not null,
  primary key (code, version, lot_from),
  foreign key (code, version) references tab.aql_scheme (code, version),
  foreign key (code, version, level_i) references tab.aql_letter (code, version, letter),
  foreign key (code, version, level_ii) references tab.aql_letter (code, version, letter),
  foreign key (code, version, level_iii) references tab.aql_letter (code, version, letter)
);

create table tab.aql_plan (
  code         text not null,
  version      text not null,
  severity     text not null check (severity in ('NORMAL', 'TIGHTENED')),
  letter       text not null,
  aql          text not null check (aql ~ '^[0-9]+\.[0-9]+$'),
  plan_letter  text not null,
  sample_size  bigint not null check (sample_size > 0),
  ac           bigint not null check (ac >= 0),
  re           bigint not null check (re = ac + 1),
  primary key (code, version, severity, letter, aql),
  foreign key (code, version, letter) references tab.aql_letter (code, version, letter),
  foreign key (code, version, plan_letter) references tab.aql_letter (code, version, letter)
);

create table tab.aql_lot_result (
  id            uuid primary key default gen_random_uuid(),
  batch_id      uuid not null references recipe.batch_execution (id),
  installation  text not null,
  product_code  text not null check (btrim(product_code) <> ''),
  step_key      text not null check (btrim(step_key) <> ''),
  entry_id      text not null check (entry_id ~ '^EN-[1-9][0-9]{0,8}$'),
  severity      text not null check (severity in ('NORMAL', 'TIGHTENED')),
  accepted      boolean not null,
  recorded_at   timestamptz not null default clock_timestamp(),
  unique (batch_id, entry_id)
);
create index aql_lot_result_by_product on tab.aql_lot_result (product_code, installation, recorded_at);

