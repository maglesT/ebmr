/**
 * The SQL primitives (ADR 0023, decision 2): the few parts of the vocabulary whose SQL reading is more than an
 * operator, written once here as functions the generated rules call. Each is the twin of a part of interpret.ts, and
 * the conformance suite (test/conformance.test.ts) runs them against it on real PostgreSQL 16.
 *
 * They are emitted by the generator like the rules (fixed text, in this order, each between its markers), so rules:check
 * covers them too.
 */

export interface Primitive {
  /** The function, schema-qualified, as the markers name it. */
  readonly name: string;
  /** What it is the twin of, for the block's header. */
  readonly doc: string;
  /** The `create or replace function` statement and its comment, without the markers. */
  readonly sql: string;
}

/** A computed key (interpret.ts `path`): a JSON string's text; anything else is no key (NULL, so `->` gives NULL). */
const KEY: Primitive = {
  name: 'recipe.rules_key',
  doc: 'A computed path step: the text of a JSON string, NULL for anything else (interpret.ts, path).',
  sql: `create or replace function recipe.rules_key(k jsonb)
returns text
language sql immutable parallel safe
as $rule$
select case when jsonb_typeof(k) = 'string' then k #>> '{}' end
$rule$;
comment on function recipe.rules_key(jsonb) is 'Generated by @ebmr/rules (ADR 0023): a computed path step, the text of a JSON string or NULL.';`,
};

/**
 * Membership (interpret.ts `in`): an element equal to the value, by jsonb equality. Not `@>`: containment would find
 * `[1]` in `[[1, 2]]` and `{"a": 1}` in `[{"a": 1, "b": 2}]`, which equality does not.
 */
const MEMBER: Primitive = {
  name: 'recipe.rules_member',
  doc: 'Membership: whether a JSON array has an element equal to the value; false for ABSENT or a non-array (interpret.ts, in).',
  sql: `create or replace function recipe.rules_member(v jsonb, list jsonb)
returns boolean
language sql immutable parallel safe
as $rule$
select exists (
  select 1
    from jsonb_array_elements(case when jsonb_typeof(list) = 'array' then list end) as e(x)
   where e.x = v
)
$rule$;
comment on function recipe.rules_member(jsonb, jsonb) is 'Generated by @ebmr/rules (ADR 0023): whether a JSON array has an element equal to the value.';`,
};

/**
 * A decimal (interpret.ts `decimal`, through @ebmr/expr Dec.parse): a JSON number, or a string Dec.parse accepts: at
 * most 400 characters of an optional minus, digits, an optional point and fraction and an optional exponent; at most
 * 34 significant digits; a non-zero value's leading digit at 10^-1000 to 10^1000. Anything else is no decimal (NULL),
 * never an error. The value is written out without an exponent before the cast, because numeric input refuses an
 * exponent beyond 1000 that a value in range can still need (34 digits at 10^-1000).
 */
const DECIMAL: Primitive = {
  name: 'recipe.rules_decimal',
  doc: 'A decimal: a JSON number, or a string that @ebmr/expr Dec.parse accepts, as an exact numeric; NULL otherwise (interpret.ts, decimal).',
  sql: `create or replace function recipe.rules_decimal(x jsonb)
returns numeric
language plpgsql immutable parallel safe
as $rule$
declare
  t text;
  m text[];
  digits text;
  significant text;
  exp_digits text;
  e integer;
  plain text;
begin
  if jsonb_typeof(x) is distinct from 'number' and jsonb_typeof(x) is distinct from 'string' then
    return null;
  end if;
  t := x #>> '{}';
  if length(t) > 400 then
    return null;
  end if;
  m := regexp_match(t, '^(-?)([0-9]+)(?:\\.([0-9]+))?(?:[eE]([+-]?)([0-9]+))?$');
  if m is null then
    return null;
  end if;
  digits := m[2] || coalesce(m[3], '');
  significant := btrim(digits, '0');
  if significant = '' then
    return 0;
  end if;
  if length(significant) > 34 then
    return null;
  end if;
  exp_digits := ltrim(coalesce(m[5], ''), '0');
  if length(exp_digits) > 6 then
    return null;
  end if;
  -- The power of ten of the leading significant digit.
  e := length(m[2]) - 1 - (length(digits) - length(ltrim(digits, '0')))
       + (case when m[4] = '-' then -1 else 1 end) * coalesce(nullif(exp_digits, '')::integer, 0);
  if e > 1000 or e < -1000 then
    return null;
  end if;
  if e >= length(significant) - 1 then
    plain := significant || repeat('0', e - length(significant) + 1);
  elsif e >= 0 then
    plain := left(significant, e + 1) || '.' || substr(significant, e + 2);
  else
    plain := '0.' || repeat('0', -e - 1) || significant;
  end if;
  return (m[1] || plain)::numeric;
end
$rule$;
comment on function recipe.rules_decimal(jsonb) is 'Generated by @ebmr/rules (ADR 0023): a JSON number or a decimal string Dec.parse accepts, as exact numeric; NULL otherwise.';`,
};

export const PRIMITIVES: readonly Primitive[] = [KEY, MEMBER, DECIMAL];
