/**
 * The generated SQL (ADR 0023, decisions 2, 3, 9 and 10): one block per primitive and per catalogued definition, each
 * between `-- @ebmr/rules begin <function>` and `-- @ebmr/rules end <function>` lines, with a header naming the source
 * definition, its sha256 and the generator's version. The same definitions always give the same bytes: blocks in a
 * fixed order, object keys sorted, and nothing from the clock, the machine or the file system.
 */
import { createHash } from 'node:crypto';
import { CATALOG, FIELD_RULE_INPUTS, type CatalogEntry, type Definition } from '../catalog.ts';
import { PACKAGE } from '../version.ts';
import { canonicalJson, compileBool, GenerateError, IDENTIFIER, jsonbLiteral, quote, rootIdentifier } from './compile.ts';
import { PRIMITIVES } from './primitives.ts';

export interface Block {
  /** The function, schema-qualified (`recipe.rule_<name>` or a primitive's name). */
  readonly fn: string;
  /** The whole block, its markers included, ending in a newline. */
  readonly text: string;
}

export const BEGIN = '-- @ebmr/rules begin ';
export const END = '-- @ebmr/rules end ';

const sha256 = (text: string): string => createHash('sha256').update(text).digest('hex');

/** The hash a generated function's header names: of the definition as canonical JSON (kind and body). */
export const definitionHash = (d: Definition): string => sha256(canonicalJson(d));

const comment = (text: string): string =>
  text
    .split('\n')
    .map((l) => `-- ${l}`.trimEnd())
    .join('\n');

const wrap = (fn: string, header: string[], sql: string): Block => ({
  fn,
  text: `${BEGIN}${fn}\n${comment(header.join('\n'))}\n${sql}\n${END}${fn}\n`,
});

function functionName(name: string): string {
  if (!IDENTIFIER.test(name) || name.length > 58) throw new GenerateError(`the rule name "${name}" is not a lower-case identifier of at most 58 characters`);
  return `recipe.rule_${name}`;
}

/** A dollar-quoted body; refuses one that holds the quote's own tag. */
function body(sql: string): string {
  if (sql.includes('$rule$')) throw new GenerateError('a generated body holds "$rule$", the tag of its own quote');
  return `as $rule$\n${sql}\n$rule$;`;
}

function header(entry: CatalogEntry): string[] {
  const { definition: d } = entry;
  return [
    `Generated by ${PACKAGE.name} ${PACKAGE.version} (pnpm rules:generate). Do not edit: change the definition and generate.`,
    `Source: ${entry.source} ${entry.exportName} (${d.kind} ${d.def.name}, version ${d.def.version}).`,
    `Definition sha256: ${definitionHash(d)}`,
    ...d.def.doc.split('\n'),
  ];
}

function definitionBlock(entry: CatalogEntry): Block {
  const { definition: d } = entry;
  const fn = functionName(d.def.name);
  if (d.kind === 'predicate') {
    const roots = new Set(d.def.inputs);
    if (roots.size !== d.def.inputs.length) throw new GenerateError(`${d.def.name} names an input twice`);
    const params = d.def.inputs.map((r) => `${rootIdentifier(r)} jsonb`).join(', ');
    const sql = [
      `create or replace function ${fn}(${params})`,
      'returns boolean',
      'language sql immutable parallel safe',
      body(`select ${compileBool(d.def.body, roots)}`),
      `comment on function ${fn}(${d.def.inputs.map(() => 'jsonb').join(', ')}) is ${quote(`Generated by ${PACKAGE.name} (ADR 0023) from ${entry.source} ${entry.exportName}: ${d.def.doc}`)};`,
    ].join('\n');
    return wrap(fn, header(entry), sql);
  }
  const roots = new Set<string>(FIELD_RULE_INPUTS);
  const raises = d.def.raise;
  const lines = [
    'select case',
    `  -- applies\n  when not ${compileBool(d.def.applies, roots, '  ')} then null`,
    `  -- breached\n  when not ${compileBool(d.def.breached, roots, '  ')} then null`,
  ];
  // The interpreter takes the first entry whose `when` holds; one without a `when` catches the rest, and the entries
  // after it are never reached (here they are not written).
  let closed = false;
  for (const r of raises) {
    if (r.when === undefined) {
      lines.push(`  else ${jsonbLiteral(r.then)}`);
      closed = true;
      break;
    }
    lines.push(`  when ${compileBool(r.when, roots, '  ')} then ${jsonbLiteral(r.then)}`);
  }
  // With no entry left to choose, the interpreter requires nothing (`find` gives undefined): SQL's case gives NULL.
  if (!closed) lines.push('  else null');
  lines.push('end');
  const params = FIELD_RULE_INPUTS.map((r) => `${rootIdentifier(r)} jsonb`).join(', ');
  const sql = [
    `create or replace function ${fn}(${params})`,
    'returns jsonb',
    'language sql immutable parallel safe',
    body(lines.join('\n')),
    `comment on function ${fn}(${FIELD_RULE_INPUTS.map(() => 'jsonb').join(', ')}) is ${quote(`Generated by ${PACKAGE.name} (ADR 0023) from ${entry.source} ${entry.exportName}: ${d.def.doc}`)};`,
  ].join('\n');
  return wrap(fn, header(entry), sql);
}

/** Every block the generator writes: the primitives first (the rules call them), then the definitions by function name. */
export function generateBlocks(catalog: readonly CatalogEntry[] = CATALOG): Block[] {
  const prims = PRIMITIVES.map((p) =>
    wrap(p.name, [`Generated by ${PACKAGE.name} ${PACKAGE.version} (pnpm rules:generate). Do not edit: change the generator and generate.`, `Primitive: ${p.doc}`, `Body sha256: ${sha256(p.sql)}`], p.sql),
  );
  // A rule's function is recipe.rule_<name> and a primitive's recipe.rules_<name>, so only two definitions can collide.
  const defs = new Map<string, Block>();
  for (const b of catalog.map(definitionBlock)) {
    if (defs.has(b.fn)) throw new GenerateError(`two definitions generate ${b.fn}`);
    defs.set(b.fn, b);
  }
  // Strings sort in code-unit order, the same on every machine.
  return [...prims, ...[...defs.keys()].sort().map((fn) => defs.get(fn) as Block)];
}

/** A new migration holding `blocks`, with the header every migration of the package carries. */
export function migrationText(blocks: readonly Block[]): string {
  return [
    `-- Generated SQL of the GMP entry rules (ADR 0023): ${blocks.map((b) => b.fn).join(', ')}.`,
    '-- Handbook: modules/rules.md',
    '--',
    '-- Written by pnpm rules:generate from packages/rules. Each block between its "@ebmr/rules begin" and "end" lines is',
    "-- the generator's output, byte for byte; rules:check (a static check) fails when the latest committed block of a",
    '-- generated function differs from it, or when a migration defines one outside its markers. Lines outside the blocks',
    '-- (this header) may be edited before the migration is first applied, like any other migration.',
    '',
    'set local role ebmr_owner;',
    '',
    blocks.map((b) => b.text).join('\n'),
    'reset role;',
    '',
  ].join('\n');
}
