/**
 * The SQL generator and rules:check (ADR 0023, decisions 3, 9 and 10): deterministic output with a header naming the
 * source, its hash and the generator's version; a check that fails on any drift between the committed migrations and
 * the generator; refusals of what the generated SQL could not hold.
 */
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { beforeEach, describe, expect, it } from 'vitest';
import { CATALOG, type CatalogEntry } from '../src/catalog.ts';
import { canonicalJson, compile, compileBool, GenerateError, jsonbLiteral, quote } from '../src/generate/compile.ts';
import { BEGIN, definitionHash, END, generateBlocks, migrationText, type Block } from '../src/generate/emit.ts';
import { check, committed, nextFile, pending, readMigrations, type Migration } from '../src/generate/migrations.ts';
import { PRIMITIVES } from '../src/generate/primitives.ts';
import { FIELD_SHOWN, UNEXPECTED_ANSWER } from '../src/library.ts';
import { PACKAGE } from '../src/version.ts';
import { and, lit, not, or, path, present, same, type FieldRule, type Predicate } from '../src/vocabulary.ts';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));

/** The same value with every object's keys in reverse order. */
function reversed<T>(value: T): T {
  if (Array.isArray(value)) return value.map(reversed) as T;
  if (typeof value === 'object' && value !== null) {
    return Object.fromEntries(Object.entries(value).reverse().map(([k, x]) => [k, reversed(x)])) as T;
  }
  return value;
}

const mig = (file: string, text: string): Migration => ({ file, text });

describe('the SQL generator', () => {
  it('[meta] is deterministic: the same definitions give the same bytes, whatever the order of their keys', () => {
    const once = generateBlocks();
    expect(generateBlocks()).toEqual(once);
    expect(generateBlocks(reversed(CATALOG))).toEqual(once);
    expect(migrationText(once)).toBe(migrationText(generateBlocks()));
    // Nothing from the machine, the file system or the clock.
    const text = migrationText(once);
    expect(text).not.toMatch(/\/home\/|\/tmp\/|\\Users\\|20\d\d-\d\d-\d\d|T\d\d:\d\d/);
    expect(text).not.toContain(ROOT);
  });

  it('[meta] writes the primitives first, then the definitions by function name, each between its markers', () => {
    const blocks = generateBlocks();
    expect(blocks.map((b) => b.fn)).toEqual(['recipe.rules_key', 'recipe.rules_member', 'recipe.rules_decimal', 'recipe.rule_library_field_shown', 'recipe.rule_library_unexpected_answer']);
    for (const b of blocks) {
      const lines = b.text.split('\n');
      expect(lines[0]).toBe(`${BEGIN}${b.fn}`);
      expect(lines.at(-2)).toBe(`${END}${b.fn}`);
      expect(lines.at(-1)).toBe('');
      expect(b.text).toContain(`create or replace function ${b.fn}(`);
    }
    const shuffled: CatalogEntry[] = [...CATALOG].reverse();
    expect(generateBlocks(shuffled).map((b) => b.fn)).toEqual(blocks.map((b) => b.fn));
  });

  it('[meta] names the source definition, its sha256 and the generator version in each header; the hash follows the definition', () => {
    const [shown] = generateBlocks().filter((b) => b.fn === 'recipe.rule_library_field_shown');
    const d = { kind: 'predicate', def: FIELD_SHOWN } as const;
    expect(shown?.text).toContain(`-- Generated by ${PACKAGE.name} ${PACKAGE.version} (pnpm rules:generate).`);
    expect(shown?.text).toContain('-- Source: packages/rules/src/library.ts FIELD_SHOWN (predicate library_field_shown, version 1).');
    expect(shown?.text).toContain(`-- Definition sha256: ${definitionHash(d)}`);
    expect(definitionHash(d)).toMatch(/^[0-9a-f]{64}$/);
    expect(definitionHash(reversed(d))).toBe(definitionHash(d));
    expect(definitionHash({ kind: 'predicate', def: { ...FIELD_SHOWN, version: 2 } })).not.toBe(definitionHash(d));
    expect(definitionHash({ kind: 'predicate', def: { ...FIELD_SHOWN, body: not(FIELD_SHOWN.body) } })).not.toBe(definitionHash(d));
    for (const p of PRIMITIVES) {
      const block = generateBlocks().find((b) => b.fn === p.name);
      expect(block?.text).toMatch(/-- Body sha256: [0-9a-f]{64}\n/);
      expect(block?.text).toContain(p.sql);
    }
  });

  it('[meta] a predicate is a boolean SQL function of its inputs; a field rule a jsonb function of field, values and config', () => {
    const [shown, unexpected] = generateBlocks().slice(3);
    expect(shown?.text).toContain('create or replace function recipe.rule_library_field_shown("field" jsonb, "values" jsonb)\nreturns boolean\nlanguage sql immutable parallel safe\nas $rule$\nselect (');
    expect(shown?.text).toContain('comment on function recipe.rule_library_field_shown(jsonb, jsonb) is \'Generated by @ebmr/rules (ADR 0023) from packages/rules/src/library.ts FIELD_SHOWN: ');
    expect(unexpected?.text).toContain('create or replace function recipe.rule_library_unexpected_answer("field" jsonb, "values" jsonb, "config" jsonb)\nreturns jsonb\n');
    expect(unexpected?.text).toContain(`  when ("field" -> 'unexpectedCritical' is not distinct from 'true'::jsonb) then '{"category":"OUT_OF_LIMIT","controls":["PR-29"],"severity":"CRITICAL","type":"LIB_UNEXPECTED_ANSWER"}'::jsonb\n  else '{"category":"OUT_OF_LIMIT","controls":["PR-29"],"severity":"ACTION","type":"LIB_UNEXPECTED_ANSWER"}'::jsonb\nend\n`);
  });

  it('[meta] a field rule whose every entry has a `when` requires nothing when none holds; entries after one without a `when` are not written', () => {
    const raise = UNEXPECTED_ANSWER.raise;
    const onlyWhen: FieldRule = { ...UNEXPECTED_ANSWER, name: 'only_when', raise: [raise[0] as FieldRule['raise'][number]] };
    const text = generateBlocks([{ source: 's.ts', exportName: 'X', definition: { kind: 'field-rule', def: onlyWhen } }]).at(-1)?.text;
    expect(text).toContain('  else null\nend');
    const unreachable: FieldRule = { ...UNEXPECTED_ANSWER, name: 'unreachable', raise: [raise[1] as FieldRule['raise'][number], raise[0] as FieldRule['raise'][number]] };
    const text2 = generateBlocks([{ source: 's.ts', exportName: 'Y', definition: { kind: 'field-rule', def: unreachable } }]).at(-1)?.text ?? '';
    expect(text2).not.toContain('CRITICAL');
    expect(text2).not.toContain('else null');
  });

  it('[meta] writes one clause per line for and/or, indented by depth', () => {
    const roots = new Set(['v']);
    expect(compileBool(and(), roots)).toBe('true');
    expect(compileBool(or(), roots)).toBe('false');
    expect(compileBool(and(path('v', 'a')), roots)).toBe('("v" -> \'a\' is not distinct from \'true\'::jsonb)');
    expect(compileBool(and(present(path('v', 'a')), or(present(path('v', 'b')), present(path('v', 'c')))), roots)).toBe(
      '(\n  ("v" -> \'a\' is not null)\n  and (\n    ("v" -> \'b\' is not null)\n    or ("v" -> \'c\' is not null)\n  )\n)',
    );
    expect(compile(path('v'), roots)).toEqual({ kind: 'json', text: '"v"' });
    expect(compile(or(present(path('v', 'a')), present(path('v', 'b'))), roots)).toEqual({ kind: 'bool', text: '(\n  ("v" -> \'a\' is not null)\n  or ("v" -> \'b\' is not null)\n)' });
    expect(compile(same(present(present(path('v'))), present(path('v', 'x'))), roots).text).toBe('(true = ("v" -> \'x\' is not null))');
    expect(compile(same(present(path('v')), lit(true)), roots).text).toBe("(to_jsonb((\"v\" is not null)) is not distinct from 'true'::jsonb)");
  });

  it('[meta] refuses what the generated SQL could not hold or would misread', () => {
    const roots = new Set(['v']);
    expect(() => compile(path('w', 'a'), roots)).toThrow(GenerateError);
    expect(() => compile(path('v', 'a\u0000'), roots)).toThrow(/NUL/);
    expect(() => jsonbLiteral('a\u0000')).toThrow(GenerateError);
    expect(() => jsonbLiteral('\ud800')).toThrow(GenerateError);
    expect(() => canonicalJson(undefined)).toThrow(GenerateError);
    expect(quote("it's")).toBe("'it''s'");
    const bad = (def: Predicate) => () => generateBlocks([{ source: 's.ts', exportName: 'X', definition: { kind: 'predicate', def } }]);
    expect(bad({ ...FIELD_SHOWN, name: 'Bad-Name' })).toThrow(/identifier/);
    expect(bad({ ...FIELD_SHOWN, name: 'x'.repeat(59) })).toThrow(/58/);
    expect(bad({ ...FIELD_SHOWN, name: 'x'.repeat(58) })).not.toThrow();
    expect(bad({ ...FIELD_SHOWN, inputs: ['field', 'values', 'field'] })).toThrow(/twice/);
    expect(bad({ ...FIELD_SHOWN, inputs: ['field', 'Values'] })).toThrow(/identifier/);
    expect(bad({ ...FIELD_SHOWN, body: same(path('field', 'a'), lit('$rule$')) })).toThrow(/\$rule\$/);
    const twice = { source: 's.ts', exportName: 'X', definition: { kind: 'predicate', def: FIELD_SHOWN } } as const;
    expect(() => generateBlocks([twice, twice])).toThrow('two definitions generate recipe.rule_library_field_shown');
  });

  it('[meta] says what it refused, and refuses an unholdable string anywhere in a literal (keys included)', () => {
    expect(() => compile(path('w', 'a'), new Set(['v', 'x']))).toThrow('the input "w" is not one of this rule\'s inputs (v, x)');
    expect(() => canonicalJson(undefined)).toThrow('undefined is not a JSON value');
    expect(() => jsonbLiteral('a\u0000')).toThrow('the literal "a\\u0000" holds a character jsonb cannot hold');
    expect(() => jsonbLiteral(['ok', { k: '\ud800' }])).toThrow('the literal ["ok",{"k":"\\ud800"}] holds a character jsonb cannot hold (a NUL or a lone surrogate)');
    expect(() => jsonbLiteral({ ['k\udc00']: 1 })).toThrow(GenerateError);
    expect(() => jsonbLiteral([['\u0000']])).toThrow(GenerateError);
    expect(() => jsonbLiteral(['ok', '\ud800'])).toThrow(GenerateError);
    expect(() => jsonbLiteral({ ok: 'x', bad: '\udfff' })).toThrow(GenerateError);
    expect(jsonbLiteral(null)).toBe("'null'::jsonb");
    expect(jsonbLiteral(['\ud83d\ude00', { a: null }, 1, true])).toBe('\'["\ud83d\ude00",{"a":null},1,true]\'::jsonb');
    // A key whose value is undefined is left out, as JSON.stringify leaves it out.
    expect(canonicalJson({ b: 1, a: undefined, c: [true] })).toBe('{"b":1,"c":[true]}');
    expect(() => compile(path('v', 'a'), new Set(['Values']))).toThrow('the input "v" is not one of');
    expect(() => compile(path('Values', 'a'), new Set(['Values']))).toThrow('the input name "Values" is not a lower-case identifier');
  });

  it('[meta] writes the definitions in code-unit order of their functions, whatever the catalogue\'s order', () => {
    const entry = (name: string): CatalogEntry => ({ source: 's.ts', exportName: name.toUpperCase(), definition: { kind: 'predicate', def: { ...FIELD_SHOWN, name } } });
    const fns = generateBlocks([entry('c'), entry('a_b'), entry('b'), entry('a')]).slice(PRIMITIVES.length).map((b) => b.fn);
    expect(fns).toEqual(['recipe.rule_a', 'recipe.rule_a_b', 'recipe.rule_b', 'recipe.rule_c']);
  });

  it('[meta] writes a multi-line doc as comment lines (a blank line as a bare "--") and indents a field rule\'s clauses', () => {
    const rule: FieldRule = {
      name: 'demo',
      version: 3,
      doc: 'First line.\n\nThird line.',
      applies: present(path('field', 'id')),
      breached: and(present(path('values', 'x')), present(path('values', 'y'))),
      raise: [
        { when: or(present(path('config', 'a')), present(path('config', 'b'))), then: { type: 'T', severity: 'CRITICAL', category: 'C', controls: [] } },
        { then: { type: 'T', severity: 'ACTION', category: 'C', controls: ['PR-29'] } },
      ],
    };
    const text = generateBlocks([{ source: 'packages/rules/src/demo.ts', exportName: 'DEMO', definition: { kind: 'field-rule', def: rule } }]).at(-1)?.text;
    expect(text).toBe(
      [
        '-- @ebmr/rules begin recipe.rule_demo',
        `-- Generated by @ebmr/rules ${PACKAGE.version} (pnpm rules:generate). Do not edit: change the definition and generate.`,
        '-- Source: packages/rules/src/demo.ts DEMO (field-rule demo, version 3).',
        `-- Definition sha256: ${definitionHash({ kind: 'field-rule', def: rule })}`,
        '-- First line.',
        '--',
        '-- Third line.',
        'create or replace function recipe.rule_demo("field" jsonb, "values" jsonb, "config" jsonb)',
        'returns jsonb',
        'language sql immutable parallel safe',
        'as $rule$',
        'select case',
        '  -- applies',
        '  when not ("field" -> \'id\' is not null) then null',
        '  -- breached',
        '  when not (',
        '    ("values" -> \'x\' is not null)',
        '    and ("values" -> \'y\' is not null)',
        '  ) then null',
        '  when (',
        '    ("config" -> \'a\' is not null)',
        '    or ("config" -> \'b\' is not null)',
        '  ) then \'{"category":"C","controls":[],"severity":"CRITICAL","type":"T"}\'::jsonb',
        '  else \'{"category":"C","controls":["PR-29"],"severity":"ACTION","type":"T"}\'::jsonb',
        'end',
        '$rule$;',
        'comment on function recipe.rule_demo(jsonb, jsonb, jsonb) is \'Generated by @ebmr/rules (ADR 0023) from packages/rules/src/demo.ts DEMO: First line.',
        '',
        'Third line.\';',
        '-- @ebmr/rules end recipe.rule_demo',
        '',
      ].join('\n'),
    );
  });
});

describe('rules:check and rules:generate', () => {
  // Built inside each test, not when the file is collected, so a mutant of the generator is run per test.
  let blocks: Block[];
  let good: Migration;
  let old: Migration;
  beforeEach(() => {
    blocks = generateBlocks();
    good = mig('1930_rules.sql', migrationText(blocks));
    old = mig('0170_batch_issue.sql', 'create or replace function recipe.rule_table_versions() returns int language sql as $$ select 1 $$;');
  });

  it('[meta] the repository passes rules:check: every generated function\'s latest committed block is the generator\'s output', () => {
    expect(check(readMigrations(ROOT))).toEqual([]);
    expect(pending(readMigrations(ROOT))).toEqual([]);
  });

  it('[meta] passes the generator\'s own migration, ignores hand-written functions that only share the prefix, and reads the latest block', () => {
    expect(check([old, good])).toEqual([]);
    expect(pending([old, good])).toEqual([]);
    const changed = generateBlocks([{ ...(CATALOG[0] as CatalogEntry), definition: { kind: 'predicate', def: { ...FIELD_SHOWN, version: 2 } } }, CATALOG[1] as CatalogEntry]);
    const later = mig('1931_rules.sql', migrationText(pending([good], changed)));
    expect(pending([good], changed).map((b) => b.fn)).toEqual(['recipe.rule_library_field_shown']);
    expect(check([good, later], changed)).toEqual([]);
    // Against the current definitions the later block is the drift.
    expect(check([good, later])).toEqual(['recipe.rule_library_field_shown: its latest block (1931_rules.sql) differs from the generator\'s output (run pnpm rules:generate)']);
    expect(committed([good, later], blocks).latest.get('recipe.rule_library_field_shown')?.file).toBe('1931_rules.sql');
  });

  it('[meta] fails on a missing block, an edited block, a definition outside the markers, a broken marker and a block with no definition', () => {
    expect(check([old])).toEqual(blocks.map((b) => `${b.fn}: no migration holds its generated block (run pnpm rules:generate)`));
    const edited = mig('1930_rules.sql', good.text.replace("'\"YES_NO\"'::jsonb", "'\"YES-NO\"'::jsonb"));
    expect(check([edited])).toEqual(['recipe.rule_library_unexpected_answer: its latest block (1930_rules.sql) differs from the generator\'s output (run pnpm rules:generate)']);
    expect(pending([edited]).map((b) => b.fn)).toEqual(['recipe.rule_library_unexpected_answer']);
    const outside = mig('1931_hand.sql', 'create or replace function recipe.rule_library_field_shown("field" jsonb, "values" jsonb) returns boolean language sql as $$ select true $$;\nCREATE FUNCTION Recipe.Rules_Extra (x jsonb) returns int language sql as $$ select 1 $$;');
    expect(check([good, outside])).toEqual([
      '1931_hand.sql: defines recipe.rule_library_field_shown outside the generator\'s markers (generated functions are only written by pnpm rules:generate)',
      '1931_hand.sql: defines recipe.rules_extra outside the generator\'s markers (generated functions are only written by pnpm rules:generate)',
    ]);
    const unclosed = mig('1931_x.sql', `${BEGIN}recipe.rules_key\nselect 1;\n`);
    expect(check([good, unclosed])).toEqual(['1931_x.sql:1: the block of recipe.rules_key is not closed by "-- @ebmr/rules end recipe.rules_key" before another marker']);
    const nested = mig('1931_x.sql', `${BEGIN}recipe.rules_key\n${BEGIN}recipe.rules_member\n${END}recipe.rules_key\n`);
    expect(check([good, nested])[0]).toMatch(/^1931_x\.sql:1: the block of recipe\.rules_key is not closed/);
    const stray = mig('1931_x.sql', `select 1;\n${END}recipe.rules_key\n`);
    expect(check([good, stray])).toEqual([`1931_x.sql:2: "${END}recipe.rules_key" closes no block`]);
    const dup = mig('1931_x.sql', `${blocks[0]?.text ?? ''}${blocks[0]?.text ?? ''}`);
    expect(check([good, dup])).toEqual([`1931_x.sql:${String((blocks[0]?.text.split('\n').length ?? 0))}: a second block of recipe.rules_key`]);
    const gone = mig('1931_x.sql', `${BEGIN}recipe.rule_retired\nselect 1;\n${END}recipe.rule_retired\n`);
    expect(check([good, gone])).toEqual(['recipe.rule_retired: generated in 1931_x.sql, but no definition or primitive generates it any more']);
    // A function the generator once wrote is still its own: a later hand-written definition is refused.
    const handAfterRetired = mig('1932_y.sql', 'create function recipe.rule_retired() returns int language sql as $$ select 1 $$;');
    expect(check([good, gone, handAfterRetired])).toContain('1932_y.sql: defines recipe.rule_retired outside the generator\'s markers (generated functions are only written by pnpm rules:generate)');
  });

  it('[meta] numbers the next migration one above the highest, or as asked, and never takes a number in use', () => {
    const ms = [mig('0001_a.sql', ''), mig('1926_b.sql', ''), mig('README.sql', '')];
    expect(nextFile(ms, 'generated')).toBe('1927_rules_generated.sql');
    expect(nextFile(ms, 'x', 1930)).toBe('1930_rules_x.sql');
    expect(nextFile(ms, 'x', 2)).toBe('0002_rules_x.sql');
    expect(() => nextFile(ms, 'Bad slug', 1930)).toThrow('a migration slug is lower-case letters, digits and underscores, not "Bad slug"');
    expect(() => nextFile(ms, 'ok slug', 1930)).toThrow(/slug/);
    expect(nextFile(ms, 'x', 9999)).toBe('9999_rules_x.sql');
    expect(nextFile([mig('0007_a.sql', ''), mig('0010_b.sql', ''), mig('0009_c.sql', '')], 'x')).toBe('0011_rules_x.sql');
    expect(() => nextFile(ms, 'x', 1926)).toThrow('migration number 1926 is taken by 1926_b.sql');
    expect(() => nextFile(ms, 'x', 0)).toThrow('a migration number is 1 to 9999, not 0');
    expect(() => nextFile(ms, 'x', 10000)).toThrow(/1 to 9999/);
    expect(() => nextFile(ms, 'x', Number.NaN)).toThrow(/1 to 9999/);
    expect(nextFile([], 'x')).toBe('0001_rules_x.sql');
  });

  it('[meta] reads the migrations in the migrator\'s order (names sorted), .sql files only, as text', () => {
    const root = mkdtempSync(join(tmpdir(), 'ebmr-rules-'));
    try {
      const dir = join(root, 'packages/recipe-core/sql');
      mkdirSync(dir, { recursive: true });
      for (const f of ['1931_b.sql', '0002_a.sql', 'notes.md', '1930_c.sql']) writeFileSync(join(dir, f), `-- ${f}\n`);
      expect(readMigrations(root)).toEqual([mig('0002_a.sql', '-- 0002_a.sql\n'), mig('1930_c.sql', '-- 1930_c.sql\n'), mig('1931_b.sql', '-- 1931_b.sql\n')]);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('[meta] pending is every block before any migration holds one; a hand definition is refused even before the first block is committed', () => {
    expect(pending([], blocks)).toEqual(blocks);
    const hand = mig('1931_hand.sql', 'create or replace\nfunction recipe.rule_library_field_shown("field" jsonb, "values" jsonb) returns boolean language sql as $$ select true $$;');
    expect(check([hand], blocks)).toContain('1931_hand.sql: defines recipe.rule_library_field_shown outside the generator\'s markers (generated functions are only written by pnpm rules:generate)');
  });

  it('[meta] a block holding another function\'s end marker is not closed', () => {
    const other = mig('1931_x.sql', `${BEGIN}recipe.rules_key\nselect 1;\n${END}recipe.rules_member\nselect 2;\n${END}recipe.rules_key\n`);
    expect(check([good, other])).toEqual([
      '1931_x.sql:1: the block of recipe.rules_key is not closed by "-- @ebmr/rules end recipe.rules_key" before another marker',
      `1931_x.sql:3: "${END}recipe.rules_member" closes no block`,
      `1931_x.sql:5: "${END}recipe.rules_key" closes no block`,
    ]);
    const empty = mig('1931_y.sql', `${BEGIN}recipe.rules_key\n${END}recipe.rules_key\n`);
    expect(check([good, empty])).toEqual(['recipe.rules_key: its latest block (1931_y.sql) differs from the generator\'s output (run pnpm rules:generate)']);
  });

  it('[meta] a migration it writes carries the handbook line, the owner role and its reset', () => {
    expect(migrationText(blocks).split('\n').slice(0, 10)).toEqual([
      `-- Generated SQL of the GMP entry rules (ADR 0023): ${blocks.map((b) => b.fn).join(', ')}.`,
      '-- Handbook: modules/rules.md',
      '--',
      '-- Written by pnpm rules:generate from packages/rules. Each block between its "@ebmr/rules begin" and "end" lines is',
      "-- the generator's output, byte for byte; rules:check (a static check) fails when the latest committed block of a",
      '-- generated function differs from it, or when a migration defines one outside its markers. Lines outside the blocks',
      '-- (this header) may be edited before the migration is first applied, like any other migration.',
      '',
      'set local role ebmr_owner;',
      '',
    ]);
    const text = migrationText(blocks);
    expect(text.endsWith(`\n${blocks.at(-1)?.text ?? ''}\nreset role;\n`)).toBe(true);
    expect(text).toContain(`\n\n${blocks[0]?.text ?? ''}\n${blocks[1]?.text ?? ''}\n`);
    const head = text.split('\n').slice(0, 10);
    expect(head).toContain('-- Handbook: modules/rules.md');
    expect(text).toContain('\nset local role ebmr_owner;\n');
    expect(text.endsWith('\nreset role;\n')).toBe(true);
    expect(text.split('\n')[0]).toBe(`-- Generated SQL of the GMP entry rules (ADR 0023): ${blocks.map((b) => b.fn).join(', ')}.`);
  });
});

