/**
 * Quality and master data at the site (Phase 3 slice 5a; slice 5 plan, defaults D-S5-1 to D-S5-9): deviation-lite,
 * the evidence-document store, the ERP product master and the QC decision on extra testing. Thin wrappers over the
 * database commands of sql/0730 to 0733: every rule is enforced there, under the application role.
 *
 * Every function runs inside a command (the kernel's withCommand). Instants are ISO 8601 text read from the database.
 */
import type { Queryable } from '../batch-numbers/register.ts';

export type DeviationKind = 'DEVIATION' | 'OOS' | 'INVESTIGATION';
export type DeviationClassification = 'MINOR' | 'MAJOR' | 'CRITICAL';
export type DeviationState = 'OPEN' | 'UNDER_INVESTIGATION' | 'CONCLUDED' | 'CLOSED' | 'CANCELLED';
export type DeviationSubjectKind = 'BATCH' | 'LOT' | 'CONTAINER';
export type DeviationRefUse = 'LINK' | 'DISPOSITION' | 'INVALIDATION' | 'REPROCESSING';
export type RootCauseCategory = 'HUMAN_ERROR' | 'EQUIPMENT' | 'MATERIAL' | 'METHOD' | 'ENVIRONMENT' | 'PROCESS' | 'LABORATORY_ERROR' | 'NOT_DETERMINED';

export interface NewDeviation {
  kind: DeviationKind;
  title: string;
  description?: string;
  classification: DeviationClassification;
  riskRationale: string;
}

export interface DeviationFinding {
  assignableCause: boolean;
  cause: string;
  rootCauseCategory: RootCauseCategory;
}

async function one<T>(client: Queryable, text: string, values: unknown[]): Promise<T> {
  const { rows } = await client.query(text, values);
  return (rows[0] as { r: T }).r;
}

/** Raises a record at the session's site; the reference is generated by the database (DEVIATION.RAISE). */
export function raiseDeviation(client: Queryable, d: NewDeviation): Promise<{ deviationId: string; ref: string; state: DeviationState }> {
  return one(client, 'select site.raise_deviation($1::jsonb) as r', [JSON.stringify(d)]);
}

export function linkDeviation(client: Queryable, deviationId: string, subjectKind: DeviationSubjectKind, subjectId: string): Promise<string> {
  return one(client, 'select site.link_deviation($1, $2, $3) as r', [deviationId, subjectKind, subjectId]);
}

export async function startDeviationInvestigation(client: Queryable, deviationId: string): Promise<void> {
  await client.query('select site.start_deviation_investigation($1)', [deviationId]);
}

export function recordDeviationFinding(client: Queryable, deviationId: string, f: DeviationFinding): Promise<string> {
  return one(client, 'select site.record_deviation_finding($1, $2::jsonb) as r', [deviationId, JSON.stringify(f)]);
}

/** QA's conclusion with its DEVIATION_CONCLUDED signature on aggregate deviation:<id> (QA other than the initiator). */
export async function concludeDeviation(client: Queryable, deviationId: string, signatureId: string): Promise<void> {
  await client.query('select site.conclude_deviation($1, $2)', [deviationId, signatureId]);
}

export async function closeDeviation(client: Queryable, deviationId: string, signatureId: string): Promise<void> {
  await client.query('select site.close_deviation($1, $2)', [deviationId, signatureId]);
}

export async function cancelDeviation(client: Queryable, deviationId: string, reason: string): Promise<void> {
  await client.query('select site.cancel_deviation($1, $2)', [deviationId, reason]);
}

export function deviationState(client: Queryable, deviationId: string): Promise<DeviationState | null> {
  return one(client, 'select site.deviation_state($1) as r', [deviationId]);
}

/** NULL when GMP batch `batchId` may cite `ref` for `use`, else why not (D-S2-2). */
export function deviationRefProblem(client: Queryable, ref: string, use: DeviationRefUse, batchId: string): Promise<string | null> {
  return one(client, 'select site.deviation_ref_problem($1, $2, $3) as r', [ref, use, batchId]);
}

export interface EvidenceDocument {
  /** SHA-256 of the bytes, 64 lower-case hex digits. */
  sha256: string;
  mediaType: string;
  /** Decimal string. */
  sizeBytes: string;
  storageKey: string;
  title: string;
}

export function registerEvidenceDocument(client: Queryable, doc: EvidenceDocument): Promise<string> {
  return one(client, 'select site.register_evidence_document($1::jsonb) as r', [JSON.stringify(doc)]);
}

export function evidenceDocumentProblem(client: Queryable, documentId: string, siteCode: string): Promise<string | null> {
  return one(client, 'select site.evidence_document_problem($1, $2) as r', [documentId, siteCode]);
}

export interface ErpProduct {
  productCode: string;
  strength: string;
  productName: string;
  /** Defaults to false in the database (D-S5-5). */
  reprocessingPermitted?: boolean;
  betaLactam: boolean;
  shelfLifeMonths: number;
  erpReference: string;
}

/**
 * The ERP interface posts a product master version (ERP.MASTER_WRITE, sql/0802). It takes effect at once only when the
 * version in effect has the same reprocessing permission and shelf life; otherwise, and for a new product, once QA
 * confirms it (confirmErpMaster).
 */
export function erpReceiveProduct(client: Queryable, p: ErpProduct): Promise<string> {
  return one(client, 'select site.erp_receive_product($1::jsonb) as r', [JSON.stringify(p)]);
}

export type ErpMasterKind = 'PRODUCT' | 'MATERIAL';

/** The aggregate QA signs (ERP_MASTER_CONFIRMED) to confirm a received master version (sql/0802). */
export const erpMasterAggregateId = (kind: ErpMasterKind, versionId: string): string => `${kind}/${versionId}`;

/** QA confirms a received master version with its ERP_MASTER_CONFIRMED signature (ERP.MASTER_CONFIRM; sql/0802). */
export async function confirmErpMaster(client: Queryable, kind: ErpMasterKind, versionId: string, signatureId: string): Promise<void> {
  await client.query('select site.confirm_erp_master($1, $2, $3)', [kind, versionId, signatureId]);
}

export interface ErpMasterPending {
  masterKind: ErpMasterKind;
  key: string;
  versionId: string;
  erpReference: string;
  receivedAt: string;
  values: Record<string, unknown>;
  inEffect: Record<string, unknown> | null;
}

/** The latest received master versions not yet in effect, with the values in effect beside them (sql/0802). */
export function erpMasterPending(client: Queryable): Promise<ErpMasterPending[]> {
  return one(client, 'select site.erp_master_pending() as r', []);
}

export interface ProductMaster {
  reprocessingPermitted: boolean;
  betaLactam: boolean;
  shelfLifeMonths: number;
}

export function productMasterOf(client: Queryable, productCode: string, strength: string): Promise<ProductMaster | null> {
  return one(client, 'select site.product_master_of($1, $2) as r', [productCode, strength]);
}

export type QcExtraTestingDecision = 'NONE_REQUIRED' | 'EXTRA_TESTS';

/** The aggregate id QC signs (QC_EXTRA_TESTING_DECIDED) for the decision: it binds the batch, the decision and the tests. */
export function qcExtraTestingAggregateId(client: Queryable, batchId: string, decision: QcExtraTestingDecision, tests: readonly string[]): Promise<string> {
  return one(client, 'select site.qc_extra_testing_aggregate_id($1, $2, $3::text[]) as r', [batchId, decision, tests]);
}

export function recordQcExtraTestingDecision(
  client: Queryable,
  batchId: string,
  decision: QcExtraTestingDecision,
  tests: readonly string[],
  signatureId: string,
): Promise<string> {
  return one(client, 'select site.record_qc_extra_testing_decision($1, $2, $3::text[], $4) as r', [batchId, decision, tests, signatureId]);
}

export function qcExtraTestingDecisionOf(
  client: Queryable,
  batchId: string,
): Promise<{ decision: QcExtraTestingDecision; tests: string[]; signatureId: string; decidedAt: string } | null> {
  return one(client, 'select site.qc_extra_testing_decision_of($1) as r', [batchId]);
}
