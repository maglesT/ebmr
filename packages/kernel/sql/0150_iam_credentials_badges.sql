-- Active badges whose last passing test is older than the test interval.
create function iam.badges_due_for_test(p_at timestamptz default null) returns table (
  badge_id uuid, account_id uuid, label text, last_passed_at timestamptz, due_at timestamptz, overdue boolean)
language sql stable security definer set search_path = pg_catalog, iam, pg_temp as $$
  with t as (select coalesce(p_at, clock_timestamp()) as at)
  select b.id, b.account_id, b.label, lt.last_pass,
         lt.last_pass + make_interval(days => iam.policy_int('badge.test_interval_days')::int),
         coalesce(lt.last_pass + make_interval(days => iam.policy_int('badge.test_interval_days')::int) <= t.at, true)
  from t cross join iam.badge b
  left join lateral (select max(x.recorded_at) as last_pass from iam.badge_test x where x.badge_id = b.id and x.result = 'PASS') lt on true
  where b.status = 'ACTIVE'
  order by 5 nulls first
$$;

-- ---------------------------------------------------------------------------------------------
-- Break-glass windows (DI-18: sealed, time-limited, dual authorisation, alarm on use, reviewed
-- afterwards, no GMP action)
-- ---------------------------------------------------------------------------------------------

create table iam.break_glass_window (
  id                    uuid primary key default gen_random_uuid(),
  account_id            uuid not null references iam.account (id),
  requested_by_person   uuid not null,
  requested_by_account  uuid not null,
  reason                text not null check (btrim(reason) <> ''),
  valid_minutes         integer not null check (valid_minutes > 0),
  requested_at          timestamptz not null default clock_timestamp(),
  approved_by_person    uuid,
  approved_by_account   uuid,
  approved_at           timestamptz,
  valid_to              timestamptz,
  reviewed_by_person    uuid,
  reviewed_at           timestamptz,
  review_outcome        text check (review_outcome in ('NO_FINDINGS', 'FINDINGS_RAISED')),
  review_comment        text,
  check (approved_by_person is null or approved_by_person <> requested_by_person),
  check (reviewed_by_person is null or reviewed_by_person <> requested_by_person)
);

create function iam.break_glass_guard() returns trigger
language plpgsql security definer set search_path = pg_catalog, iam, pg_temp as $$
declare
  v_acc iam.account%rowtype;
begin
  select * into v_acc from iam.account where id = new.account_id;
  if tg_op = 'INSERT' then
    if not v_acc.is_break_glass then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-130 break-glass windows are for break-glass accounts only';
    end if;
    if new.valid_minutes > iam.policy_int('breakglass.max_window_minutes') then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-130 the break-glass window is longer than policy allows';
    end if;
    if new.approved_by_person is not null or new.reviewed_by_person is not null then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-130 a break-glass window is requested first';
    end if;
    new.requested_at := clock_timestamp();
    return new;
  end if;
  if new.id <> old.id or new.account_id <> old.account_id or new.requested_by_person <> old.requested_by_person
     or new.reason <> old.reason or new.valid_minutes <> old.valid_minutes or new.requested_at <> old.requested_at then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-007 a break-glass request never changes';
  end if;
  if old.approved_by_person is null and new.approved_by_person is not null then
    if new.approved_by_person = v_acc.person_id then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-003 the break-glass holder cannot approve their own window';
    end if;
    new.approved_at := clock_timestamp();
    new.valid_to := new.approved_at + make_interval(mins => new.valid_minutes);
  elsif new.approved_by_person is distinct from old.approved_by_person or new.approved_at is distinct from old.approved_at
        or new.valid_to is distinct from old.valid_to then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-130 a break-glass approval happens once and never changes';
  end if;
  if old.reviewed_by_person is null and new.reviewed_by_person is not null then
    if old.approved_at is null or clock_timestamp() < old.valid_to then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-130 a break-glass window is reviewed after it ends';
    end if;
    new.reviewed_at := clock_timestamp();
  elsif new.reviewed_by_person is distinct from old.reviewed_by_person or new.reviewed_at is distinct from old.reviewed_at
        or new.review_outcome is distinct from old.review_outcome or new.review_comment is distinct from old.review_comment then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-130 a break-glass review happens once and never changes';
  end if;
  return new;
end
$$;
create trigger aa_break_glass_guard before insert or update on iam.break_glass_window for each row execute function iam.break_glass_guard();

create function iam.request_break_glass(p_account uuid, p_reason text, p_minutes integer) returns uuid
language plpgsql volatile security definer set search_path = pg_catalog, iam, kernel, pg_temp as $$
declare
  v_actor jsonb := iam.require_permission('SYSTEM.CONFIGURE', '{}'::jsonb);
  v_id    uuid;
begin
  if (select person_id from iam.account where id = p_account) is distinct from (v_actor ->> 'person_id')::uuid then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-130 a break-glass window is requested by the holder of that break-glass account';
  end if;
  insert into iam.break_glass_window (account_id, requested_by_person, requested_by_account, reason, valid_minutes)
  values (p_account, (v_actor ->> 'person_id')::uuid, (v_actor ->> 'account_id')::uuid, p_reason, p_minutes)
  returning id into v_id;
  return v_id;
end
$$;

create function iam.approve_break_glass(p_window uuid) returns void
language plpgsql volatile security definer set search_path = pg_catalog, iam, kernel, pg_temp as $$
declare
  v_actor jsonb := iam.require_permission('IAM.BREAK_GLASS_APPROVE', '{}'::jsonb);
begin
  update iam.break_glass_window set approved_by_person = (v_actor ->> 'person_id')::uuid, approved_by_account = (v_actor ->> 'account_id')::uuid
   where id = p_window and approved_by_person is null;
  if not found then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-130 no pending break-glass request with that id';
  end if;
end
$$;

create function iam.review_break_glass(p_window uuid, p_outcome text, p_comment text) returns void
language plpgsql volatile security definer set search_path = pg_catalog, iam, kernel, pg_temp as $$
declare
  v_actor jsonb := iam.require_permission('IAM.BREAK_GLASS_APPROVE', '{}'::jsonb);
begin
  update iam.break_glass_window set reviewed_by_person = (v_actor ->> 'person_id')::uuid, review_outcome = p_outcome, review_comment = p_comment
   where id = p_window and reviewed_by_person is null;
  if not found then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-130 no unreviewed break-glass window with that id';
  end if;
end
$$;

create function iam.break_glass_open(p_account uuid, p_at timestamptz) returns uuid
language sql stable security definer set search_path = pg_catalog, iam, pg_temp as $$
  select w.id from iam.break_glass_window w
  where w.account_id = p_account and w.approved_at is not null and w.approved_at <= p_at and p_at < w.valid_to
  order by w.approved_at desc limit 1
$$;

