create function iam.badge_uid_hash(p_uid text) returns bytea
language plpgsql stable security definer set search_path = pg_catalog, iam, pg_temp as $$
declare
  v_uid text := upper(regexp_replace(coalesce(p_uid, ''), '[:\s-]', '', 'g'));
begin
  if v_uid !~ '^[0-9A-F]{8,64}$' then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-060 a badge UID is 8-64 hexadecimal digits';
  end if;
  return sha256((select value from iam.installation_secret where name = 'badge_uid_pepper') || convert_to(v_uid, 'UTF8'));
end
$$;

create function iam.badge_guard() returns trigger
language plpgsql security definer set search_path = pg_catalog, iam, kernel, pg_temp as $$
declare
  v_actor uuid := nullif(kernel.current_actor() ->> 'person_id', '')::uuid;
  v_iv    iam.identity_verification%rowtype;
  v_last  timestamptz;
begin
  if tg_op = 'INSERT' then
    if new.status <> 'ISSUED' then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-061 a badge is issued, then tested, then activated';
    end if;
    if not (select secure from iam.badge_technology where code = new.technology) then
      raise exception using errcode = 'P0001', message = format('EBMR-IAM-060 badge technology %s is clonable and not accepted', new.technology);
    end if;
    select * into v_iv from iam.identity_verification where id = new.identity_verification_id;
    if v_iv.person_id <> new.person_id then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-063 the identity verification is for another person';
    end if;
    -- A replacement (any badge after the first) needs identity re-verified after the last badge event.
    select max(b.status_changed_at) into v_last from iam.badge b where b.person_id = new.person_id;
    if v_last is not null and (v_iv.purpose <> 'BADGE_REPLACEMENT' or v_iv.recorded_at <= v_last) then
      raise exception using errcode = 'P0001',
        message = 'EBMR-IAM-063 DI-19: a replacement badge needs the identity re-verified (purpose BADGE_REPLACEMENT) after the previous badge''s last change';
    end if;
    if v_last is null and iam.current_identity_verification(new.person_id) is null then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-013 DI-15: no identity-verification record; no badge can be issued';
    end if;
    new.issued_at := clock_timestamp();
    new.status_changed_at := new.issued_at;
    return new;
  end if;
  if new.id <> old.id or new.account_id <> old.account_id or new.person_id <> old.person_id or new.label <> old.label
     or new.technology <> old.technology or new.replaces_badge_id is distinct from old.replaces_badge_id
     or new.identity_verification_id <> old.identity_verification_id or new.issued_by_person <> old.issued_by_person
     or new.issued_at <> old.issued_at then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-007 a badge record never changes except its status';
  end if;
  if new.status is distinct from old.status then
    if not ((old.status = 'ISSUED' and new.status in ('ACTIVE', 'REVOKED'))
         or (old.status = 'ACTIVE' and new.status in ('LOST', 'REVOKED', 'REPLACED'))) then
      raise exception using errcode = 'P0001', message = format('EBMR-IAM-061 a badge cannot go from %s to %s', old.status, new.status);
    end if;
    -- Only reporting one's own badge lost is self-service; everything else is another person's act.
    if v_actor = old.person_id and new.status <> 'LOST' then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-003 nobody administers their own badge';
    end if;
    if new.status = 'ACTIVE' and not exists (
         select 1 from iam.badge_test t where t.badge_id = new.id and t.kind = 'AT_ISSUE' and t.result = 'PASS'
           and not exists (select 1 from iam.badge_test f where f.badge_id = new.id and f.result = 'FAIL' and f.recorded_at > t.recorded_at)) then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-062 DI-19: a badge is activated only after a passing test at issue';
    end if;
    new.status_changed_at := clock_timestamp();
  end if;
  return new;
end
$$;
create trigger aa_badge_guard before insert or update on iam.badge for each row execute function iam.badge_guard();

create function iam.badge_test_guard() returns trigger
language plpgsql security definer set search_path = pg_catalog, iam, pg_temp as $$
begin
  new.recorded_at := clock_timestamp();
  if new.tested_by_person = (select person_id from iam.badge where id = new.badge_id) then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-003 nobody records a test of their own badge';
  end if;
  return new;
end
$$;
create trigger aa_badge_test_guard before insert on iam.badge_test for each row execute function iam.badge_test_guard();

create function iam.issue_badge(p_account uuid, p_uid text, p_technology text, p_label text, p_identity_verification uuid,
                                p_replaces uuid default null) returns uuid
language plpgsql volatile security definer set search_path = pg_catalog, iam, kernel, pg_temp as $$
declare
  v_actor jsonb := iam.require_permission('IAM.CREDENTIAL_ISSUE', '{}'::jsonb);
  v_acc   iam.account%rowtype;
  v_hash  bytea := iam.badge_uid_hash(p_uid);
  v_id    uuid;
begin
  select * into v_acc from iam.account where id = p_account;
  if not found or v_acc.kind <> 'HUMAN' or v_acc.is_generic or v_acc.status in ('DISABLED') then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-061 badges are issued to personal human accounts that are not disabled';
  end if;
  if exists (select 1 from iam.badge_secret where uid_hash = v_hash) then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-060 this badge UID was issued before and is never issued again';
  end if;
  if p_replaces is not null and not exists (select 1 from iam.badge where id = p_replaces and person_id = v_acc.person_id) then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-063 a replacement replaces a badge of the same person';
  end if;
  insert into iam.badge (account_id, person_id, label, technology, replaces_badge_id, identity_verification_id, issued_by_person, issued_by_account)
  values (v_acc.id, v_acc.person_id, p_label, p_technology, p_replaces, p_identity_verification, (v_actor ->> 'person_id')::uuid,
          (v_actor ->> 'account_id')::uuid)
  returning id into v_id;
  insert into iam.badge_secret (badge_id, uid_hash) values (v_id, v_hash);
  return v_id;
end
$$;

