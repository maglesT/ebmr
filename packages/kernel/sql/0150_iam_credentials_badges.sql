create table iam.credential (
  id                 uuid primary key default gen_random_uuid(),
  account_id         uuid not null references iam.account (id),
  kind               text not null check (kind in ('PASSWORD', 'PIN', 'SERVICE_KEY')),
  origin             text not null check (origin in ('INITIAL', 'ADMIN_RESET', 'USER_CHANGE', 'SERVICE_ISSUE', 'BOOTSTRAP')),
  must_change        boolean not null,
  status             text not null default 'ACTIVE' check (status in ('ACTIVE', 'SUPERSEDED', 'REVOKED')),
  issued_by_person   uuid not null,
  issued_by_account  uuid not null,
  issued_at          timestamptz not null default clock_timestamp(),
  expires_at         timestamptz,
  ended_at           timestamptz,
  end_reason         text,
  check (must_change = (origin in ('INITIAL', 'ADMIN_RESET', 'BOOTSTRAP'))),
  check ((status = 'ACTIVE') = (ended_at is null))
);
create unique index credential_one_active on iam.credential (account_id, kind) where status = 'ACTIVE';

create table iam.credential_secret (
  credential_id  uuid primary key references iam.credential (id),
  verifier       text not null,
  created_at     timestamptz not null default clock_timestamp()
);
select iam.protect_log('iam.credential_secret');

-- argon2id PHC string with at least the OWASP baseline parameters (m=19456 KiB, t=2, p=1).
create function iam.check_verifier(p_verifier text) returns text
language plpgsql immutable set search_path = pg_catalog, pg_temp as $$
declare
  m text[] := regexp_match(coalesce(p_verifier, ''),
                           '^\$argon2id\$v=19\$m=([0-9]{1,10}),t=([0-9]{1,10}),p=([0-9]{1,3})\$[A-Za-z0-9+/]{16,}\$[A-Za-z0-9+/]{32,}$');
begin
  if m is null then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-050 a verifier must be an argon2id (v=19) PHC string; plaintext is never stored';
  end if;
  if m[1]::bigint < 19456 or m[2]::bigint < 2 or m[3]::bigint < 1 then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-050 argon2id parameters are below the minimum m=19456, t=2, p=1';
  end if;
  return p_verifier;
end
$$;

create function iam.credential_guard() returns trigger
language plpgsql security definer set search_path = pg_catalog, iam, kernel, pg_temp as $$
declare
  v_actor  uuid := nullif(kernel.current_actor() ->> 'person_id', '')::uuid;
  v_person uuid := (select person_id from iam.account where id = new.account_id);
  v_aging  bigint;
begin
  if tg_op = 'INSERT' then
    if new.status <> 'ACTIVE' or new.ended_at is not null then
      raise exception using errcode = 'P0001', message = 'EBMR-IAM-051 a credential is issued ACTIVE';
    end if;
    -- Only the owner changes their own secret; nobody else issues a secret to themselves.
    if (new.origin = 'USER_CHANGE') <> (v_actor is not distinct from v_person) then
      raise exception using errcode = 'P0001',
        message = 'EBMR-IAM-003 a user changes only their own secret, and an administrator never issues a secret to their own account';
    end if;
    new.issued_at := clock_timestamp();
    if new.must_change then
      new.expires_at := new.issued_at + make_interval(hours => iam.policy_int('credential.initial_secret_valid_hours')::int);
    elsif new.kind = 'PASSWORD' then
      v_aging := iam.policy_int('credential.password_max_age_days');
      new.expires_at := case when v_aging > 0 then new.issued_at + make_interval(days => v_aging::int) end;
    else
      new.expires_at := null;
    end if;
    return new;
  end if;
  if new.id <> old.id or new.account_id <> old.account_id or new.kind <> old.kind or new.origin <> old.origin
     or new.must_change <> old.must_change or new.issued_by_person <> old.issued_by_person or new.issued_at <> old.issued_at
     or new.expires_at is distinct from old.expires_at or old.status <> 'ACTIVE' or new.status not in ('SUPERSEDED', 'REVOKED') then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-051 a credential only ends (superseded or revoked), once';
  end if;
  new.ended_at := clock_timestamp();
  return new;
end
$$;
create trigger aa_credential_guard before insert or update on iam.credential for each row execute function iam.credential_guard();

-- Internal: end the active credential of a kind and store a new one with its verifier.
create function iam.store_credential(p_account uuid, p_kind text, p_origin text, p_verifier text, p_actor jsonb) returns uuid
language plpgsql volatile security definer set search_path = pg_catalog, iam, pg_temp as $$
declare
  v_id uuid;
begin
  perform iam.check_verifier(p_verifier);
  update iam.credential set status = 'SUPERSEDED', end_reason = 'replaced by a new ' || lower(p_origin) || ' secret'
   where account_id = p_account and kind = p_kind and status = 'ACTIVE';
  insert into iam.credential (account_id, kind, origin, must_change, issued_by_person, issued_by_account)
  values (p_account, p_kind, p_origin, p_origin in ('INITIAL', 'ADMIN_RESET', 'BOOTSTRAP'), (p_actor ->> 'person_id')::uuid,
          (p_actor ->> 'account_id')::uuid)
  returning id into v_id;
  insert into iam.credential_secret (credential_id, verifier) values (v_id, p_verifier);
  return v_id;
end
$$;

-- Administrator issue or reset of a secret. The verifier is computed by the authentication
-- service from a secret it generated and delivers to the user; the administrator never sees it.
create function iam.issue_credential(p_account uuid, p_kind text, p_verifier text) returns uuid
language plpgsql volatile security definer set search_path = pg_catalog, iam, kernel, pg_temp as $$
declare
  v_actor  jsonb := iam.require_permission('IAM.CREDENTIAL_ISSUE', '{}'::jsonb);
  v_acc    iam.account%rowtype;
  v_origin text;
begin
  select * into v_acc from iam.account where id = p_account;
  if not found then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-022 unknown account';
  end if;
  if v_acc.status = 'DISABLED' then
    raise exception using errcode = 'P0001', message = 'EBMR-IAM-026 a disabled account receives no credentials';
  end if;
  if (p_kind = 'SERVICE_KEY') <> (v_acc.kind in ('SERVICE', 'INTEGRATION')) then
    raise exception using errcode = 'P0001',
      message = 'EBMR-IAM-051 service and integration accounts use service keys only; people use passwords and PINs';
  end if;
  if v_acc.kind in ('HUMAN', 'READONLY_DISPLAY') and iam.current_identity_verification(v_acc.person_id) is null then
    raise exception using errcode = 'P0001',
      message = 'EBMR-IAM-013 DI-15: no identity-verification record; no signature component can be issued';
  end if;
  v_origin := case when p_kind = 'SERVICE_KEY' then 'SERVICE_ISSUE'
                   when exists (select 1 from iam.credential where account_id = p_account and kind = p_kind) then 'ADMIN_RESET'
                   else 'INITIAL' end;
  return iam.store_credential(p_account, p_kind, v_origin, p_verifier, v_actor);
end
$$;

create function iam.revoke_credentials(p_account uuid, p_reason text) returns void
language plpgsql volatile security definer set search_path = pg_catalog, iam, pg_temp as $$
begin
  update iam.credential set status = 'REVOKED', end_reason = p_reason where account_id = p_account and status = 'ACTIVE';
end
$$;

