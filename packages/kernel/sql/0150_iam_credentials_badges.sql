-- Identity and access (B1), part 6: credentials, badges and break-glass windows (DI-15, DI-18,
-- DI-19; outline 4.7 badges and credentials).
--
-- Secrets and the audit trail. A credential has two rows:
--   iam.credential         metadata only (kind, origin, must-change flag, status, expiry, who issued
--                          it). Audited on the account chain, so every issue, reset, change and
--                          revocation is in the hash-chained trail.
--   iam.credential_secret  the argon2id verifier. Not audited (audit diffs must never contain
--                          verifiers), insert-only, and readable by nobody but ebmr_owner: the
--                          application role cannot read or write it; the authentication service
--                          reads verifiers only through iam.authn_prepare for the account being
--                          authenticated. A secret is never updated in place: a new secret is a new
--                          credential row plus a new secret row, so the metadata trail shows every
--                          change without exposing the verifier.
-- Badge UIDs are stored only as a peppered SHA-256 in iam.badge_secret (same protection); the
-- pepper lives in iam.installation_secret, readable only by ebmr_owner.
-- Plaintext secrets exist only in the authentication service (TypeScript); administrators issue
-- initial and reset secrets generated by the service and delivered to the user, never shown to
-- the administrator; they are single-use and must be changed before the account can sign.

set local role ebmr_owner;

create table iam.installation_secret (
  name   text primary key,
  value  bytea not null
);
insert into iam.installation_secret (name, value)
values ('badge_uid_pepper', sha256(convert_to(gen_random_uuid()::text || gen_random_uuid()::text || gen_random_uuid()::text
                                              || clock_timestamp()::text, 'UTF8')));
select iam.protect_log('iam.installation_secret');

