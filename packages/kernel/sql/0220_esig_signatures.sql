-- Schema-qualified table name, whatever the caller's search_path.
create function esig.table_name_of(p_table regclass) returns text
language sql stable security definer set search_path = pg_catalog, pg_temp as $$
  select n.nspname || '.' || c.relname from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid = c.relnamespace where c.oid = p_table
$$;

-- Transaction lock per signed record: signing and changing the same record are serialised, so a
-- change can never slip between the hash check of a signing and its commit (INV-09).
create function esig.aggregate_lock(p_aggregate_type text, p_aggregate_id text) returns void
language sql volatile security definer set search_path = pg_catalog, esig, pg_temp as $$
  select pg_advisory_xact_lock(hashtextextended('esig:' || p_aggregate_type || ':' || p_aggregate_id, 0))
$$;

-- A signed record changed: log who changed it and supersede, in this transaction, every signature
-- whose content hash no longer matches the record.
create function esig.content_changed(p_aggregate_type text, p_aggregate_id text, p_table text, p_operation text) returns void
language plpgsql volatile security definer set search_path = pg_catalog, esig, iam, kernel, pg_temp as $$
declare
  v_actor    jsonb := kernel.current_actor();
  v_ref      text := p_aggregate_type || ':' || p_aggregate_id;
  v_change   bigint;
  v_hash     text;
  v_computed boolean := false;
  s          record;
begin
  perform esig.aggregate_lock(p_aggregate_type, p_aggregate_id);
  insert into esig.content_change (aggregate_type, aggregate_id, aggregate_ref, table_name, operation, person_id, account_id, correlation_id)
  values (p_aggregate_type, p_aggregate_id, v_ref, p_table, p_operation, nullif(v_actor ->> 'person_id', '')::uuid,
          nullif(v_actor ->> 'account_id', '')::uuid, nullif(v_actor ->> 'correlation_id', '')::uuid)
  returning id into v_change;
  for s in
    select g.id, g.content_hash, g.meaning_code, g.signer_legal_name, g.signer_person
    from esig.signature g
    where g.aggregate_ref = v_ref and not exists (select 1 from esig.signature_invalidation i where i.signature_id = g.id)
    order by g.recorded_at, g.id
  loop
    if not v_computed then
      v_hash := esig.content_hash_of(p_aggregate_type, p_aggregate_id, esig.provide(p_aggregate_type, p_aggregate_id));
      v_computed := true;
    end if;
    if v_hash is distinct from s.content_hash then
      insert into esig.signature_invalidation (signature_id, aggregate_ref, reason, previous_content_hash, current_content_hash, change_id,
                                               person_id, account_id, correlation_id)
      values (s.id, v_ref, 'SUPERSEDED_BY_CHANGE', s.content_hash, v_hash, v_change, nullif(v_actor ->> 'person_id', '')::uuid,
              nullif(v_actor ->> 'account_id', '')::uuid, nullif(v_actor ->> 'correlation_id', '')::uuid);
      perform kernel.audit_business_event(v_ref,
        format('signature %s (%s, %s) superseded by a change to the signed content; the element is unsigned and must be signed again',
               s.id, s.meaning_code, s.signer_legal_name),
        jsonb_build_object('signature_id', s.id, 'meaning_code', s.meaning_code, 'signer_person', s.signer_person,
                           'previous_content_hash', s.content_hash, 'current_content_hash', v_hash, 'change_table', p_table,
                           'change_operation', p_operation));
    end if;
  end loop;
end
$$;

-- Row trigger of every registered signed table.
create function esig.on_signed_content_change() returns trigger
language plpgsql volatile security definer set search_path = pg_catalog, esig, pg_temp as $$
declare
  v_reg     esig.signed_table%rowtype;
  v_new     jsonb;
  v_old     jsonb;
  v_col     text;
  v_changed boolean := false;
begin
  select * into v_reg from esig.signed_table where table_name = tg_relid;
  if not found then
    raise exception using errcode = 'P0001', message = format('EBMR-ESIG-006 %s is not registered as a signed table', esig.table_name_of(tg_relid));
  end if;
  if tg_op <> 'DELETE' then v_new := to_jsonb(new); end if;
  if tg_op <> 'INSERT' then v_old := to_jsonb(old); end if;
  if tg_op = 'UPDATE' then
    if v_new ->> v_reg.aggregate_column is distinct from v_old ->> v_reg.aggregate_column then
      v_changed := true;
    elsif v_reg.content_columns is null then
      v_changed := v_new is distinct from v_old;
    else
      foreach v_col in array v_reg.content_columns loop
        if v_new -> v_col is distinct from v_old -> v_col then
          v_changed := true;
        end if;
      end loop;
    end if;
    if not v_changed then
      return null;
    end if;
  end if;
  if v_new ->> v_reg.aggregate_column is not null then
    perform esig.content_changed(v_reg.aggregate_type, v_new ->> v_reg.aggregate_column, esig.table_name_of(tg_relid), tg_op);
  end if;
  if v_old ->> v_reg.aggregate_column is not null and v_old ->> v_reg.aggregate_column is distinct from v_new ->> v_reg.aggregate_column then
    perform esig.content_changed(v_reg.aggregate_type, v_old ->> v_reg.aggregate_column, esig.table_name_of(tg_relid), tg_op);
  end if;
  return null;
end
$$;

create function esig.forbid_truncate() returns trigger
language plpgsql security definer set search_path = pg_catalog, esig, pg_temp as $$
begin
  raise exception using errcode = 'P0001', message = format('EBMR-ESIG-007 %s holds signed content and cannot be truncated', tg_relid::regclass);
end
$$;

-- Migrations of other modules register the tables that hold signed content of an aggregate type:
--   select esig.register_signed_table('mymod.step_value', 'step', 'step_id', array['value', 'unit']);
-- content_columns NULL means every column. The aggregate type needs a content provider.
create function esig.register_signed_table(p_table regclass, p_aggregate_type text, p_aggregate_column text,
                                           p_content_columns text[] default null) returns void
language plpgsql volatile security definer set search_path = pg_catalog, esig, pg_temp as $$
declare
  v_suffix  text := replace(esig.table_name_of(p_table), '.', '_');
  v_trigger text := left('esig_signed_' || v_suffix, 63);
  v_col     text;
begin
  foreach v_col in array array[p_aggregate_column] || coalesce(p_content_columns, '{}') loop
    if not exists (select 1 from pg_catalog.pg_attribute a where a.attrelid = p_table and a.attname = v_col and a.attnum > 0 and not a.attisdropped) then
      raise exception using errcode = 'P0001', message = format('EBMR-ESIG-006 %s has no column %s', p_table, v_col);
    end if;
  end loop;
  insert into esig.signed_table (table_name, aggregate_type, aggregate_column, content_columns, trigger_name)
  values (p_table, p_aggregate_type, p_aggregate_column, p_content_columns, v_trigger);
  execute format('create trigger %I after insert or update or delete on %s for each row execute function esig.on_signed_content_change()',
                 v_trigger, p_table);
  execute format('create trigger %I before truncate on %s for each statement execute function esig.forbid_truncate()',
                 left('esig_signed_trunc_' || v_suffix, 63), p_table);
end
$$;

-- Every registered signed table still has its invalidation trigger, enabled (fail closed: no
-- challenge and no signature while one is missing).
create function esig.change_triggers_ok() returns boolean
language sql stable security definer set search_path = pg_catalog, esig, pg_temp as $$
  select not exists (
    select 1 from esig.signed_table s
    where not exists (select 1 from pg_catalog.pg_trigger t
                      where t.tgrelid = s.table_name and t.tgname = s.trigger_name and t.tgenabled in ('O', 'A')))
$$;

create function esig.assert_change_triggers_ok() returns void
language plpgsql stable security definer set search_path = pg_catalog, esig, pg_temp as $$
begin
  if not esig.change_triggers_ok() then
    raise exception using errcode = 'P0001',
      message = 'EBMR-ESIG-008 an invalidation trigger of a signed table is missing or disabled; signing is refused until it is restored (INV-09)';
  end if;
end
$$;

-- ---------------------------------------------------------------------------------------------
-- Signing failures (protected log; written after the failed command rolled back)
--
-- code and message are what the application reports; the database cannot re-check them after the
-- rollback. misuse_code and misuse_detail are what the database itself finds in committed rows
-- (the challenge and the authentication event the attempt used, DI-19): only they raise a
-- security alert, so a report can never accuse a person on the application's word alone.
-- ---------------------------------------------------------------------------------------------

create table esig.signing_failure (
  id              bigint generated always as identity primary key,
  challenge_id    uuid not null references esig.challenge (id),
  auth_event_id   uuid,
  code            text not null,
  message         text not null,
  misuse_code     text,
  misuse_detail   jsonb,
  aggregate_ref   text,
  meaning_code    text,
  signer_account  uuid,
  signer_person   uuid,
  session_id      uuid,
  device_id       uuid,
  recorded_at     timestamptz not null default clock_timestamp(),
  check ((misuse_code is null) = (misuse_detail is null))
);
create index signing_failure_auth_event on esig.signing_failure (auth_event_id) where auth_event_id is not null;
create index signing_failure_aggregate on esig.signing_failure (aggregate_ref, id);
create trigger aa_signing_failure_stamp before insert on esig.signing_failure for each row execute function esig.stamp_recorded_at();
select esig.protect_log('esig.signing_failure');

