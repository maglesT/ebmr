-- Any failure aborts everything: a transaction that inserted a signature commits only if the
-- signature was sealed in it.
create function esig.signature_sealed_check() returns trigger
language plpgsql security definer set search_path = pg_catalog, esig, pg_temp as $$
begin
  if not exists (select 1 from esig.signature_seal s where s.signature_id = new.id) then
    raise exception using errcode = 'P0001',
      message = format('EBMR-ESIG-061 signature %s was not sealed; the signing is rolled back (INV-10)', new.id);
  end if;
  return null;
end
$$;
create constraint trigger esig_signature_sealed after insert on esig.signature
  deferrable initially deferred for each row execute function esig.signature_sealed_check();

