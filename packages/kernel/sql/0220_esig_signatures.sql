-- Electronic signatures (B2), part 3: seal keys, challenges, signature rows, seals, the permanent
-- signature-ID register, invalidations, the content-change log, the signing-failure log and the
-- generic invalidation mechanism other modules register their signed tables into.
--
--   esig.challenge               single-use, 120 s, bound to record version, meaning, signer account,
--                                session and terminal (outline 5.5 step 1); insert-only, audited
--   esig.signature               written only by esig.sign (INV-10); insert-only, audited; its ID is
--                                generated by the database and entered in the permanent register
--                                (INV-27); a deferred check refuses a commit without a seal
--   esig.signature_seal          HMAC-SHA256 or Ed25519 seal over the canonical seal payload, with
--                                key ID and algorithm (agility); the key is held outside the database
--   esig.signature_invalidation  SUPERSEDED_BY_CHANGE, inserted in the same transaction as the change
--                                (INV-09); the signature row itself is never updated
--   esig.content_change          who changed which signed record, when (for INV-03 involvement)
--
-- Every signature and seal row sits in the hash-chained audit trail on chain
-- esig_signature:<aggregate_type>:<aggregate_id>; business entries go to the record's own chain.

set local role ebmr_owner;

create function esig.stamp_recorded_at() returns trigger
language plpgsql security definer set search_path = pg_catalog, esig, pg_temp as $$
begin
  new.recorded_at := clock_timestamp();
  return new;
end
$$;

