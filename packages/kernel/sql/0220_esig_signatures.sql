-- The stored manifestation (DI-36): built from the row when it is inserted, never re-derived from
-- the user tables later. Local time is computed from the stored UTC offset, so it stays identical
-- even if time-zone rules change afterwards.
create function esig.build_manifestation(s esig.signature) returns jsonb
language sql stable set search_path = pg_catalog, esig, pg_temp as $$
  select jsonb_build_object(
    'signature_id', s.id,
    'printed_name', s.signer_legal_name,
    'user_id', s.signer_login,
    'role_code', s.signer_role_code,
    'role_name', s.signer_role_name,
    'meaning_code', s.meaning_code,
    'meaning_title', s.meaning_title,
    'meaning_text', s.meaning_text,
    'signed_at_utc', esig.utc_text(s.recorded_at),
    'signed_at_local', to_char((s.recorded_at at time zone 'UTC') + s.utc_offset::interval, 'YYYY-MM-DD HH24:MI:SS'),
    'utc_offset', s.utc_offset,
    'site_zone', s.site_zone,
    'record', jsonb_build_object('aggregate_type', s.aggregate_type, 'aggregate_id', s.aggregate_id,
                                 'content_version', s.content_version::text, 'content_hash', s.content_hash),
    'cosignature', s.cosignature,
    'delegation_id', s.delegation_id)
$$;

-- One line for screen, print and PDF renderers.
create function esig.manifestation_line(m jsonb) returns text
language sql immutable strict set search_path = pg_catalog, pg_temp as $$
  select format('%s (user ID %s, %s) signed "%s": %s %s UTC%s (%s)', m ->> 'printed_name', m ->> 'user_id', m ->> 'role_name',
                m ->> 'meaning_title', m ->> 'meaning_text', m ->> 'signed_at_local', m ->> 'utc_offset', m ->> 'site_zone')
$$;

-- Only esig.sign inserts signatures: it names the challenge it is signing in a transaction-local
-- setting just before the insert, and this guard accepts exactly one row for it. The ID, time,
-- offset and manifestation are set here, whatever the inserter supplied.
create function esig.signature_guard() returns trigger
language plpgsql security definer set search_path = pg_catalog, esig, pg_temp as $$
begin
  if coalesce(current_setting('esig.signing_challenge', true), '') <> new.challenge_id::text then
    raise exception using errcode = 'P0001', message = 'EBMR-ESIG-060 INV-10: signatures are inserted only by the signing function esig.sign';
  end if;
  perform set_config('esig.signing_challenge', '', true);
  new.id := gen_random_uuid();
  new.recorded_at := clock_timestamp();
  new.utc_offset := esig.utc_offset(new.recorded_at, new.site_zone);
  new.manifestation := esig.build_manifestation(new);
  new.manifestation_text := esig.manifestation_line(new.manifestation);
  insert into esig.signature_id_register (signature_id) values (new.id);
  return new;
end
$$;
create trigger aa_signature_guard before insert on esig.signature for each row execute function esig.signature_guard();

