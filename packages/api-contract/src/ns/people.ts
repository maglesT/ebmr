/**
 * Namespace `people` (Phase 7 slice 7g-1, decision 0025): the administration of people and access on a screen. Every
 * route runs the kernel's own `iam.*` function under the person's named account, and the database decides every rule
 * (DI-14 to DI-19, INV-11): who may record a person, verify an identity, open an account, issue a credential or a badge,
 * request a role grant (the system administrator) and approve it (a second person, typically the process owner; never
 * the requester, never the grantee), recertify access (the process owner) and open a break-glass window (requested by
 * one person, approved and later reviewed by another).
 *
 * Secrets: no route returns a stored secret. An initial or reset secret is generated by the server (the kernel's
 * `issueInitialSecret`: only its argon2id verifier is stored) and returned once, by the issuing call only, for the
 * person it belongs to; it is single-use, expires and must be changed at the first sign-in (DI-15). That call is not
 * idempotent (nothing keeps the answer for a replay). A badge UID travels only in the issuing call (the database keeps
 * a peppered hash).
 */
import { z } from 'zod';
import { Instant, PersonRef, Uuid, withAttribution } from '../common.ts';
import { defineRoute } from '../route.ts';

const Text = (max: number) => z.string().trim().min(1).max(max);
const Code = z.string().trim().regex(/^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/, 'a code of letters, digits, dot, underscore or hyphen');

export const AccountKind = z.enum(['HUMAN', 'SERVICE', 'INTEGRATION', 'READONLY_DISPLAY']);
export const AccountStatus = z.enum(['PENDING_ACTIVATION', 'ACTIVE', 'SUSPENDED', 'DISABLED']);
export const CredentialKind = z.enum(['PASSWORD', 'PIN', 'SERVICE_KEY']);
export const GrantStatus = z.enum(['REQUESTED', 'APPROVED', 'REJECTED', 'REVOKED']);

export const CredentialView = z.strictObject({
  credentialId: Uuid,
  kind: CredentialKind,
  origin: z.string(),
  /** An initial or reset secret: it must be changed before the account can sign or open a session. */
  mustChange: z.boolean(),
  status: z.string(),
  issuedAt: Instant,
  expiresAt: Instant.nullable(),
});

export const BadgeView = z.strictObject({
  badgeId: Uuid,
  label: z.string(),
  technology: z.string(),
  status: z.enum(['ISSUED', 'ACTIVE', 'LOST', 'REVOKED', 'REPLACED']),
  issuedAt: Instant,
  lastTest: z.strictObject({ kind: z.string(), result: z.enum(['PASS', 'FAIL']), at: Instant }).nullable(),
});

export const GrantView = z.strictObject({
  grantId: Uuid,
  accountId: Uuid,
  loginName: z.string(),
  grantee: PersonRef,
  roleCode: z.string(),
  roleName: z.string(),
  scope: z.strictObject({ site: z.string().nullable(), area: z.string().nullable(), product: z.string().nullable() }),
  validFrom: Instant.nullable(),
  validTo: Instant.nullable(),
  reason: z.string(),
  status: GrantStatus,
  /** Approved, inside its window and not revoked. */
  live: z.boolean(),
  requestedBy: PersonRef,
  requestedAt: Instant,
  decidedBy: PersonRef.nullable(),
  decidedAt: Instant.nullable(),
  decisionReason: z.string().nullable(),
  revokedBy: PersonRef.nullable(),
  revokedAt: Instant.nullable(),
  revocationReason: z.string().nullable(),
});
export type GrantView = z.infer<typeof GrantView>;

export const AccountView = z.strictObject({
  accountId: Uuid,
  loginName: z.string(),
  kind: AccountKind,
  generic: z.boolean(),
  breakGlass: z.boolean(),
  status: AccountStatus,
  statusReason: z.string().nullable(),
  /** Locked after failed sign-ins (iam.account_locked). */
  locked: z.boolean(),
  credentials: z.array(CredentialView),
  badges: z.array(BadgeView),
  /** Role codes of the account's live grants. */
  roles: z.array(z.string()),
});
export type AccountView = z.infer<typeof AccountView>;

export const PersonView = z.strictObject({
  personId: Uuid,
  kind: z.enum(['NATURAL', 'SYSTEM']),
  legalName: z.string(),
  employeeRef: z.string().nullable(),
  status: z.enum(['ACTIVE', 'LEFT']),
  createdAt: Instant,
  verifications: z.array(
    z.strictObject({ verificationId: Uuid, purpose: z.string(), method: z.string(), documentType: z.string(), verifiedBy: PersonRef, occurredAt: Instant }),
  ),
  accounts: z.array(AccountView),
});
export type PersonView = z.infer<typeof PersonView>;

export const RoleOption = z.strictObject({ code: z.string(), name: z.string(), group: z.string(), accountKinds: z.array(z.string()) });
export type RoleOption = z.infer<typeof RoleOption>;

export const RecertificationDueView = z.strictObject({
  accountId: Uuid,
  loginName: z.string(),
  person: PersonRef,
  lastRecertifiedAt: Instant.nullable(),
  dueAt: Instant,
  overdue: z.boolean(),
  roles: z.array(z.string()),
});
export type RecertificationDueView = z.infer<typeof RecertificationDueView>;

export const RecertificationView = z.strictObject({
  recertificationId: Uuid,
  accountId: Uuid,
  loginName: z.string(),
  reviewer: PersonRef,
  outcome: z.enum(['CONFIRMED', 'REVOKED']),
  comment: z.string(),
  grantsReviewed: z.number().int().nonnegative(),
  recordedAt: Instant,
});

export const BreakGlassWindowView = z.strictObject({
  windowId: Uuid,
  accountId: Uuid,
  loginName: z.string(),
  holder: PersonRef,
  reason: z.string(),
  minutes: z.number().int().positive(),
  requestedBy: PersonRef,
  requestedAt: Instant,
  approvedBy: PersonRef.nullable(),
  approvedAt: Instant.nullable(),
  validTo: Instant.nullable(),
  state: z.enum(['REQUESTED', 'OPEN', 'ENDED', 'REVIEWED']),
  review: z.strictObject({ by: PersonRef, at: Instant, outcome: z.enum(['NO_FINDINGS', 'FINDINGS_RAISED']), comment: z.string() }).nullable(),
});
export type BreakGlassWindowView = z.infer<typeof BreakGlassWindowView>;

/** The issuing call's answer: the secret once, for its owner; never readable again. */
export const IssuedCredentialView = z.strictObject({
  credentialId: Uuid,
  accountId: Uuid,
  loginName: z.string(),
  kind: CredentialKind,
  secret: z.string().min(1),
  expiresAt: Instant.nullable(),
});
export type IssuedCredentialView = z.infer<typeof IssuedCredentialView>;

