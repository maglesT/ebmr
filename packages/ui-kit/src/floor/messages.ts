export type FloorMessageKey = keyof typeof FLOOR_EN;

/** The English text of a floor key with {placeholders} filled in. */
export function ft(key: FloorMessageKey, params: Readonly<Record<string, string | number>> = {}): string {
  return FLOOR_EN[key].replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}
