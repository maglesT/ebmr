/**
 * The demo stack (plan section 2), shared by `pnpm demo:setup`, `pnpm demo` and the E2E global set-up:
 *  - set-up: DEMO-ONLY keys (gateway Ed25519 key; the server CLI adds seal keys, secrets, terminal keys and
 *    service secrets), the exchange directory, the GMP and sandbox databases through the server's set-up CLI;
 *  - start: the GMP server, the sandbox server (with the gateway listener), the site gateway and the scale
 *    simulator, each as `node --import tsx <entry>` with prefixed logs. Missing gateway and simulator entry
 *    files are tolerated until module C5 lands.
 */
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { generateServiceKey, type SiteSeed } from '@ebmr/test-kit';
import { EXCHANGE_DIR, GATEWAY_MAIN, REPO_ROOT, SERVER_MAIN, SERVER_SETUP, SIMULATOR_MAIN, WEB_DIST, type StackPorts } from './paths.ts';
import { entryExists, runNode, spawnNode, waitForHttp, type RunningProcess } from './processes.ts';

export interface Databases {
  GMP: string;
  SANDBOX: string;
}

const README = `DEMO-ONLY key material for the eBMR demo and E2E installations.
These keys and credentials exist only in demo databases (*_demo, *_e2e_*). Never use them for a real installation.
Seal keys, terminal keys, the gateway key, service secrets and persona credentials are all generated by
\`pnpm demo:setup\` and are git-ignored.
`;

/** The gateway's Ed25519 key (DEMO-ONLY), created once and kept. Returns the SPKI (base64). */
export function ensureGatewayKey(keysDir: string): string {
  mkdirSync(keysDir, { recursive: true, mode: 0o700 });
  writeFileSync(join(keysDir, 'README.txt'), README);
  const file = join(keysDir, 'gateway-key.json');
  if (!existsSync(file)) {
    const key = generateServiceKey();
    writeFileSync(file, `${JSON.stringify({ label: 'DEMO-ONLY gateway reading-signature key (Ed25519)', ...key }, null, 2)}\n`, { mode: 0o600 });
  }
  return (JSON.parse(readFileSync(file, 'utf8')) as { publicKeySpki: string }).publicKeySpki;
}

export interface SetupStackOptions {
  databases: Databases;
  keysDir: string;
  exchangeDir?: string;
  /** Persona sets (1 for the demo; workers + 1 for E2E). */
  personaSets?: number;
  echo?: boolean;
}

/** Creates (or recreates) both databases and their DEMO-ONLY credentials. */
export async function setupStack(opts: SetupStackOptions): Promise<void> {
  const exchangeDir = opts.exchangeDir ?? EXCHANGE_DIR;
  for (const d of ['to-sandbox', 'to-gmp']) mkdirSync(join(exchangeDir, d), { recursive: true });
  const gatewaySpki = ensureGatewayKey(opts.keysDir);
  const common = ['--keys-dir', opts.keysDir, '--exchange-dir', exchangeDir, '--persona-sets', String(opts.personaSets ?? 1), '--recreate'];
  await runNode({ name: 'setup-gmp', entry: SERVER_SETUP, args: ['--installation', 'GMP', '--database', opts.databases.GMP, ...common], env: {}, echo: opts.echo ?? true });
  await runNode({
    name: 'setup-sbx',
    entry: SERVER_SETUP,
    args: ['--installation', 'SANDBOX', '--database', opts.databases.SANDBOX, '--gateway-spki', gatewaySpki, ...common],
    env: {},
    echo: opts.echo ?? true,
  });
}

/** `vite build` of the SPA (the demo and E2E serve the built output under the strict CSP). */
export function buildWeb(echo = true): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn('pnpm', ['--filter', '@ebmr/tablets-web', 'build'], { cwd: REPO_ROOT, stdio: echo ? 'inherit' : 'ignore' });
    child.once('exit', (code) => (code === 0 ? resolve() : reject(new Error(`vite build exited with code ${String(code)}`))));
  });
}

export interface StartStackOptions {
  databases: Databases;
  keysDir: string;
  ports: StackPorts;
  exchangeDir?: string;
  /** Built SPA to serve; null to serve the API only (Vite dev servers in front). */
  webDist?: string | null;
  /** Host name in the public origins (default localhost). */
  host?: string;
  echo?: boolean;
  logLevel?: string;
  /** Extra environment for both servers. */
  env?: Record<string, string>;
}

export interface RunningStack {
  urls: { gmp: string; sandbox: string; simulatorConsole: string };
  processes: RunningProcess[];
  missing: string[];
  stop(): Promise<void>;
}

function serverEnv(kind: 'GMP' | 'SANDBOX', opts: StartStackOptions, origins: { gmp: string; sandbox: string }): Record<string, string> {
  const prefix = kind === 'GMP' ? 'gmp' : 'sandbox';
  const env: Record<string, string> = {
    EBMR_INSTALLATION: kind,
    EBMR_ENV: 'development',
    EBMR_DATABASE: opts.databases[kind],
    EBMR_PUBLIC_ORIGIN: kind === 'GMP' ? origins.gmp : origins.sandbox,
    EBMR_HOST: opts.host ?? 'localhost',
    EBMR_PORT: String(kind === 'GMP' ? opts.ports.gmp : opts.ports.sandbox),
    EBMR_DEMO: '1',
    EBMR_DEMO_KEYS_FILE: join(opts.keysDir, `${prefix}-demo-devices.json`),
    EBMR_SEAL_KEY_FILE: join(opts.keysDir, `${prefix}-seal-key.json`),
    EBMR_SECRETS_FILE: join(opts.keysDir, `${prefix}-secrets.json`),
    EBMR_EXCHANGE_DIR: opts.exchangeDir ?? EXCHANGE_DIR,
    EBMR_OTHER_INSTALLATION_URL: kind === 'GMP' ? origins.sandbox : origins.gmp,
    EBMR_LOG_LEVEL: opts.logLevel ?? 'warn',
    EBMR_LOG_PRETTY: opts.echo === false ? '0' : '1',
    ...(opts.webDist === null ? {} : { EBMR_WEB_DIST: opts.webDist ?? WEB_DIST }),
    ...opts.env,
  };
  if (kind === 'SANDBOX') {
    env['EBMR_GATEWAY_LISTEN'] = `127.0.0.1:${opts.ports.gatewayListener}`;
    env['EBMR_GATEWAY_URL'] = `http://127.0.0.1:${opts.ports.gateway}`;
    env['EBMR_SERVICE_KEYS_FILE'] = join(opts.keysDir, 'sandbox-service-keys.json');
  }
  return env;
}

/** The gateway's configuration (module C5 reads it through EBMR_GW_CONFIG). */
export function writeGatewayConfig(opts: StartStackOptions): string {
  const file = join(opts.keysDir, 'gateway-config.json');
  const config = {
    label: 'DEMO-ONLY site gateway configuration (sandbox installation)',
    gatewayCode: 'TEST-GW-01',
    installation: 'SANDBOX',
    listen: `127.0.0.1:${opts.ports.gateway}`,
    uplink: `http://127.0.0.1:${opts.ports.gatewayListener}`,
    keyFile: join(opts.keysDir, 'gateway-key.json'),
    serviceKeysFile: join(opts.keysDir, 'sandbox-service-keys.json'),
    journalDir: join(opts.keysDir, '..', 'gateway-journal'),
    devices: [{ code: 'TEST-BAL-01', driver: 'mt-sics', host: '127.0.0.1', port: opts.ports.simulatorTcp, expectedSerial: 'SIM-0001', resolution: '0.001', unit: 'kg', room: 'DISP-1' }],
  };
  writeFileSync(file, `${JSON.stringify(config, null, 2)}\n`);
  return file;
}

export async function startStack(opts: StartStackOptions): Promise<RunningStack> {
  const host = opts.host ?? 'localhost';
  const origins = { gmp: `http://${host}:${opts.ports.gmp}`, sandbox: `http://${host}:${opts.ports.sandbox}` };
  const processes: RunningProcess[] = [];
  const missing: string[] = [];
  const stop = async () => {
    for (const p of [...processes].reverse()) await p.stop();
  };
  try {
    const gmp = spawnNode({ name: 'gmp', entry: SERVER_MAIN, env: serverEnv('GMP', opts, origins), echo: opts.echo ?? true });
    processes.push(gmp);
    const sbx = spawnNode({ name: 'sbx', entry: SERVER_MAIN, env: serverEnv('SANDBOX', opts, origins), echo: opts.echo ?? true });
    processes.push(sbx);
    if (entryExists(SIMULATOR_MAIN)) {
      processes.push(
        spawnNode({
          name: 'sim',
          entry: SIMULATOR_MAIN,
          env: { EBMR_SIM_TCP: `127.0.0.1:${opts.ports.simulatorTcp}`, EBMR_SIM_HTTP: `127.0.0.1:${opts.ports.simulatorHttp}`, EBMR_SIM_SERIAL: 'SIM-0001', EBMR_SIM_SEED: '42' },
          echo: opts.echo ?? true,
        }),
      );
    } else missing.push('scale simulator (apps/simulators/src/scale/main.ts, module C5)');
    if (entryExists(GATEWAY_MAIN)) {
      processes.push(spawnNode({ name: 'gw', entry: GATEWAY_MAIN, env: { EBMR_GW_CONFIG: writeGatewayConfig(opts) }, echo: opts.echo ?? true }));
    } else missing.push('site gateway (apps/site-gateway/src/main.ts, module C5)');
    await Promise.all([
      waitForHttp(`http://127.0.0.1:${opts.ports.gmp}/api/meta`, 60_000, gmp.child),
      waitForHttp(`http://127.0.0.1:${opts.ports.sandbox}/api/meta`, 60_000, sbx.child),
    ]);
  } catch (error) {
    await stop();
    throw error;
  }
  return { urls: { ...origins, simulatorConsole: `http://127.0.0.1:${opts.ports.simulatorHttp}` }, processes, missing, stop };
}

/** The DEMO-ONLY credential card printed by `pnpm demo`. */
export function credentialCard(keysDir: string): string {
  const read = (f: string): SiteSeed | null => (existsSync(join(keysDir, f)) ? (JSON.parse(readFileSync(join(keysDir, f), 'utf8')) as SiteSeed) : null);
  const lines: string[] = ['DEMO-ONLY credentials (demo databases only)'];
  for (const seed of [read('gmp-seed.json'), read('sandbox-seed.json')]) {
    if (!seed) continue;
    lines.push('', `${seed.installation} (${seed.database})`);
    for (const p of seed.personas.filter((x) => x.set === 0)) {
      const how = p.kiosk ? `badge ${p.badgeUid ?? '?'}  PIN ${p.pin ?? '?'}   (kiosk ${p.homeTerminal})` : `user ID ${p.loginName}  password ${p.password}   (${p.homeTerminal})`;
      lines.push(`  ${p.legalName.padEnd(26)} ${p.roleCode.padEnd(20)} ${how}`);
    }
  }
  return lines.join('\n');
}
