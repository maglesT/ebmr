/** Small Markdown helpers shared by the generated pages. */

/** Text safe inside a Markdown table cell (no pipe, no line break, no raw HTML). */
export function cell(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/\r?\n/g, ' ').trim();
}

/** A Markdown table. */
export function table(head: readonly string[], rows: readonly (readonly string[])[]): string {
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
}

