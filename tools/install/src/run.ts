/**
 * Performing the installer's plan (plan.ts) through an InstallEnv: the machine (realEnv) or, in the tests, a fake one.
 * A dry run performs nothing: it says what each action would do, with the files it would write (secrets masked).
 */
import { createHash, randomBytes } from 'node:crypto';
import { setupUrl, rolesOf, type Action } from './plan.ts';
import type { Answers } from './answers.ts';

export interface ExecResult {
  code: number;
  stdout: string;
  stderr: string;
}

/** What the installer does to the machine and the database (the fake one records it). */
export interface InstallEnv {
  exec(cmd: string, args: readonly string[], opts?: { asUser?: string }): Promise<ExecResult>;
  exists(path: string): boolean;
  readFile(path: string): string | null;
  writeFile(path: string, content: string, mode: number): void;
  mkdir(path: string, mode: number): void;
  /** The local clusters (pg_lsclusters): name and port. */
  clusters(): Promise<{ name: string; port: number }[]>;
  db: {
    databaseExists(adminUrl: string, database: string): Promise<boolean>;
    /** Creates and migrates a new database of the answers' kind. */
    createDatabase(adminUrl: string, a: Answers): Promise<void>;
    /** Applies the pending migrations; how many. */
    migrate(adminUrl: string, a: Answers): Promise<number>;
    markDemo(adminUrl: string, database: string): Promise<void>;
    /** Sets a login role's password (creating the backup role with its privileges when it is missing). */
    setRolePassword(adminUrl: string, a: Answers, role: string, password: string): Promise<void>;
    isBootstrapped(adminUrl: string, database: string): Promise<boolean>;
    issueSetupToken(adminUrl: string, database: string, sha256: string, minutes: number): Promise<void>;
  };
  /** True once GET `url` answers 200. */
  answers(url: string): Promise<boolean>;
  sleep(ms: number): Promise<void>;
  log(line: string): void;
}

export interface RunContext {
  dryRun: boolean;
  /** The superuser connection of this run (for LOCAL: the installer superuser's, its password new each run). */
  adminUrl: string;
  /** The password of the installer superuser of a LOCAL cluster (set by the installer-superuser action). */
  installerPassword: string | null;
  /** The login roles' passwords the role-passwords action sets (also written into the environment file). */
  rolePasswords: Readonly<Record<string, string>>;
  /** The one-time set-up token (generated by the setup-token action; returned to the caller). */
  token?: string | null;
}

const mask = (text: string): string => text.replace(/(postgres:\/\/[^:]+:)[^@]+@/g, '$1********@').replace(/("(csrfHmacKey|nonceKey)":\s*")[0-9a-f]+"/g, '$1********"');

export class InstallError extends Error {}

async function must(env: InstallEnv, cmd: string, args: readonly string[], opts?: { asUser?: string }): Promise<ExecResult> {
  const r = await env.exec(cmd, args, opts);
  if (r.code !== 0) throw new InstallError(`${cmd} ${args.join(' ')} failed (exit ${String(r.code)}): ${(r.stderr || r.stdout).trim().slice(0, 500)}`);
  return r;
}

const sqlLiteral = (s: string): string => `'${s.replace(/'/g, "''")}'`;

/** Performs `actions` (or, in a dry run, says what they would do). Returns the set-up token when one was issued. */
export async function runPlan(a: Answers, actions: readonly Action[], env: InstallEnv, ctx: RunContext): Promise<{ token: string | null; setUp: boolean }> {
  const would = (what: string): void => env.log(`${ctx.dryRun ? 'would ' : ''}${what}`);
  let token: string | null = null;
  let setUp = false;
  for (const x of actions) {
    switch (x.kind) {
      case 'check': {
        would(`check ${x.title}`);
        if (ctx.dryRun) break;
        const r = await env.exec(x.cmd, x.args);
        if (r.code !== 0 || !`${r.stdout}${r.stderr}`.includes(x.need)) throw new InstallError(`${x.title} is needed: ${x.cmd} ${x.args.join(' ')} answered ${(r.stdout || r.stderr).trim() || `exit ${String(r.code)}`}`);
        break;
      }
      case 'exec':
        would(`run ${x.cmd} ${x.args.join(' ')} (${x.title})`);
        if (!ctx.dryRun) await must(env, x.cmd, x.args, x.asUser ? { asUser: x.asUser } : undefined);
        break;
      case 'mkdir':
        would(`create the directory ${x.path}`);
        if (!ctx.dryRun) env.mkdir(x.path, x.mode);
        break;
      case 'write':
        would(`write ${x.path} (${x.title})`);
        if (ctx.dryRun) env.log(mask(x.content).replace(/^/gm, '    | '));
        else env.writeFile(x.path, x.content, x.mode);
        break;
      case 'keep':
        if (env.exists(x.path)) {
          env.log(`keep ${x.path} (${x.title}, made by an earlier run)`);
        } else {
          would(`write ${x.path} (${x.title}, generated once)`);
          if (!ctx.dryRun) env.writeFile(x.path, x.content, x.mode);
        }
        break;
      case 'cluster': {
        const found = (await env.clusters()).find((c) => c.name === x.cluster);
        if (found && found.port !== x.port) throw new InstallError(`the cluster ${x.cluster} exists on port ${String(found.port)}, not ${String(x.port)}`);
        if (found) env.log(`keep the PostgreSQL 16 cluster ${x.cluster} (port ${String(x.port)})`);
        else {
          would(`create the PostgreSQL 16 cluster ${x.cluster} on port ${String(x.port)} and start it`);
          if (!ctx.dryRun) await must(env, 'pg_createcluster', ['16', x.cluster, '--port', String(x.port), '--start']);
        }
        if (!ctx.dryRun) await must(env, 'pg_ctlcluster', ['16', x.cluster, 'start']).catch(() => undefined);
        break;
      }
      case 'installer-superuser': {
        would(`set the installer's superuser ebmr_install on the cluster ${x.cluster} (a new password each run)`);
        if (ctx.dryRun) break;
        const pw = ctx.installerPassword;
        if (!pw) throw new InstallError('no password for the installer superuser');
        const sql = `do $$ begin if exists (select 1 from pg_roles where rolname = 'ebmr_install') then alter role ebmr_install with login superuser password ${sqlLiteral(pw)}; else create role ebmr_install with login superuser password ${sqlLiteral(pw)}; end if; end $$;`;
        await must(env, 'psql', ['-p', String(x.port), '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-qAtc', sql], { asUser: 'postgres' });
        break;
      }
      case 'database': {
        if (ctx.dryRun) {
          would(`create the ${a.installation} database ${a.database} and apply every migration, or apply its pending migrations if it exists`);
          break;
        }
        if (await env.db.databaseExists(ctx.adminUrl, a.database)) {
          const n = await env.db.migrate(ctx.adminUrl, a);
          env.log(`keep the database ${a.database}: ${String(n)} pending migration(s) applied`);
        } else {
          env.log(`create the ${a.installation} database ${a.database} and apply every migration`);
          await env.db.createDatabase(ctx.adminUrl, a);
        }
        break;
      }
      case 'demo-marker':
        would(`mark ${a.database} as a demo installation`);
        if (!ctx.dryRun) await env.db.markDemo(ctx.adminUrl, a.database);
        break;
      case 'role-passwords':
        would(`set the passwords of the login roles ${rolesOf(a).join(', ')} (kept in the environment file only)`);
        if (!ctx.dryRun) for (const role of rolesOf(a)) await env.db.setRolePassword(ctx.adminUrl, a, role, ctx.rolePasswords[role] ?? '');
        break;
      case 'wait': {
        would(`wait until the server answers ${x.url}`);
        if (ctx.dryRun) break;
        let ok = false;
        for (let i = 0; i < 120 && !ok; i++) {
          ok = await env.answers(x.url);
          if (!ok) await env.sleep(1000);
        }
        if (!ok) throw new InstallError(`the server does not answer ${x.url}: read its log (journalctl -u ${a.name}, or docker compose logs)`);
        break;
      }
      case 'setup-token': {
        if (ctx.dryRun) {
          would(`print the set-up URL ${setupUrl(a)} and a one-time set-up token valid for ${String(a.tokenMinutes)} minutes (only its SHA-256 is stored)`);
          break;
        }
        if (await env.db.isBootstrapped(ctx.adminUrl, a.database)) {
          setUp = true;
          env.log(`the installation is set up already: sign in at ${setupUrl(a)}`);
          break;
        }
        token = ctx.token ?? randomBytes(32).toString('base64url');
        await env.db.issueSetupToken(ctx.adminUrl, a.database, createHash('sha256').update(token, 'utf8').digest('hex'), a.tokenMinutes);
        env.log(`open ${setupUrl(a)} and give this one-time set-up token (valid ${String(a.tokenMinutes)} minutes): ${token}`);
        break;
      }
    }
  }
  return { token, setUp };
}
