/** The generated pages: code map, database catalogue, control-to-code map, error codes. Deterministic: no dates. */
import { posix } from 'node:path';
import { HANDBOOK_DIR } from './manifest.ts';
import { CODE_KINDS, type Migration, type Model, type ModuleModel } from './model.ts';
import { compare, relLink } from './repo.ts';
import type { DbKind } from './sql.ts';
import { compareControlIds, errorCodes } from './sources.ts';

export const CODE_MAP = `${HANDBOOK_DIR}/code-map.md`;
export const DB_CATALOGUE = `${HANDBOOK_DIR}/reference/db-catalogue.md`;
export const CONTROL_MAP = `${HANDBOOK_DIR}/reference/control-map.md`;
export const ERROR_CODES = `${HANDBOOK_DIR}/reference/error-codes.md`;

const HEADER = 'Generated by `pnpm handbook` from the repository and [modules.yaml](MANIFEST); do not edit.';

function header(page: string): string {
  return HEADER.replace('MANIFEST', relLink(page, `${HANDBOOK_DIR}/modules.yaml`));
}

/** Text safe inside Markdown (no raw HTML, no table breaks). */
export function esc(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function fileLink(page: string, file: string, label = posix.basename(file)): string {
  return `[${label}](${relLink(page, file)})`;
}

function symLink(page: string, file: string, name: string): string {
  return `[\`${name}\`](${relLink(page, file)}#sym=${name})`;
}

const KIND_LABEL: Record<DbKind, string> = {
  table: 'Tables',
  view: 'Views',
  type: 'Types',
  function: 'Functions',
  procedure: 'Procedures',
  trigger: 'Triggers',
};
const KIND_ORDER: readonly DbKind[] = ['table', 'view', 'type', 'function', 'procedure', 'trigger'];

function list(items: readonly string[]): string {
  return items.length === 0 ? 'none' : items.join(', ');
}

function anchorFor(m: ModuleModel): string {
  return m.def.id;
}

export function renderCodeMap(model: Model): string {
  const page = CODE_MAP;
  const out: string[] = [];
  out.push('# Code map', '', header(page), '');
  out.push(
    'Every module of the code with all of its parts (owner decision 0014). A module is a feature: its migrations, its',
    'database objects, its server files, routes and contract file, its screens, its tests and the controls whose code or',
    'tests it holds. The [database catalogue](reference/db-catalogue.md) shows which migration holds the version in force',
    'of each database function.',
    '',
    '## Modules',
    '',
    '| Module | Title | Handbook page | Migrations | Routes | Tests | Controls |',
    '|---|---|---|---|---|---|---|',
  );
  for (const m of model.modules) {
    out.push(
      `| [${m.def.id}](#${anchorFor(m)}) | ${esc(m.def.title)} | [${m.def.page}](${m.def.page}) | ${m.migrations.length} | ${m.routes.length} | ${m.tests.length} | ${m.controls.length} |`,
    );
  }
  out.push('');
  for (const m of model.modules) {
    out.push(`## ${m.def.id}`, '');
    out.push(`**${esc(m.def.title)}.** Package \`${m.def.package}\`. Handbook: [${m.def.page}](${m.def.page}).`, '');
    if (m.migrations.length > 0) {
      out.push(`**Migrations** (${m.migrations.length}):`, '');
      const bySource = new Map<string, Migration[]>();
      for (const mig of m.migrations) bySource.set(mig.source, [...(bySource.get(mig.source) ?? []), mig]);
      for (const [source, migs] of bySource) out.push(`- \`${source}\`: ${migs.map((x) => fileLink(page, x.file)).join(', ')}`);
      out.push('');
      const objects = new Map<DbKind, Set<string>>();
      for (const mig of m.migrations) {
        for (const o of mig.objects) objects.set(o.kind, (objects.get(o.kind) ?? new Set()).add(o.name));
      }
      if (objects.size > 0) {
        out.push('**Database objects** created in these migrations:', '');
        for (const kind of KIND_ORDER) {
          const names = [...(objects.get(kind) ?? [])].sort(compare);
          if (names.length > 0) out.push(`- ${KIND_LABEL[kind]} (${names.length}): ${names.map((n) => `\`${n}\``).join(', ')}`);
        }
        out.push('');
      }
    }
    const labels: Record<(typeof CODE_KINDS)[number], string> = { server: 'Server files', contract: 'Contract', screens: 'Screens', src: 'Source' };
    for (const kind of CODE_KINDS) {
      const files = m.code[kind];
      if (files.length === 0) continue;
      out.push(`**${labels[kind]}** (${files.length}): ${files.map((f) => fileLink(page, f, f.slice(commonDir(files).length))).join(', ')}`, '');
      if (kind === 'contract' && m.routes.length > 0) {
        out.push(`**Routes** (${m.routes.length}):`, '', '| Method | Path | Route | Contract file |', '|---|---|---|---|');
        for (const r of m.routes) out.push(`| ${r.method} | \`${r.path}\` | \`${r.id}\` | ${fileLink(page, r.file)} |`);
        out.push('');
      }
    }
    if (m.tests.length > 0) {
      out.push(`**Tests** (${m.tests.length}): ${m.tests.map((f) => fileLink(page, f, f.slice(commonDir(m.tests).length))).join(', ')}`, '');
    }
    if (m.controls.length > 0) {
      out.push(`**Controls** (${m.controls.length}): ${m.controls.map((c) => fileLink(page, c.file, c.id)).join(', ')}`, '');
    }
  }
  return `${out.join('\n').trimEnd()}\n`;
}

/** The longest common folder prefix (with its slash) of a list of files. */
function commonDir(files: readonly string[]): string {
  if (files.length === 0) return '';
  let prefix = posix.dirname(files[0] ?? '') + '/';
  for (const f of files) {
    while (prefix !== '' && !f.startsWith(prefix)) {
      const up = posix.dirname(prefix.replace(/\/$/, ''));
      prefix = up === '.' || up === '/' ? '' : `${up}/`;
    }
  }
  return prefix;
}

export function renderDbCatalogue(model: Model): string {
  const page = DB_CATALOGUE;
  const defs = new Map<string, { kind: DbKind; name: string; migs: Migration[] }>();
  for (const mig of [...model.migrations].sort((a, b) => a.order - b.order)) {
    for (const o of mig.objects) {
      if (o.kind === 'table' || o.kind === 'type') continue;
      const key = `${o.kind} ${o.name}`;
      const row = defs.get(key) ?? { kind: o.kind, name: o.name, migs: [] };
      row.migs.push(mig);
      defs.set(key, row);
    }
  }
  const rows = [...defs.values()].sort((a, b) => compare(a.name, b.name) || compare(a.kind, b.kind));
  const out: string[] = ['# Database catalogue', '', header(page), ''];
  out.push(
    'Every function, procedure, trigger and view the migrations create, in name order. "Defined in" is the first',
    'migration that creates it; "Replaced in" lists every later migration that creates it again (`create or replace`, or',
    'a drop and create); the last one listed holds the version **in force**, and its link opens that definition. Tables',
    'and types are listed per module in the [code map](../code-map.md). Objects created by dynamic SQL are not listed.',
    '',
    `${rows.length} objects.`,
    '',
    '| Object | Kind | Defined in | Replaced in | Module |',
    '|---|---|---|---|---|',
  );
  for (const r of rows) {
    const first = r.migs[0] as Migration;
    const last = r.migs[r.migs.length - 1] as Migration;
    const sym = r.kind === 'trigger' ? (r.name.split(' on ')[0] ?? r.name) : r.name;
    const nameCell = `${symLink(page, last.file, sym)}${r.kind === 'trigger' ? ` on \`${r.name.split(' on ')[1] ?? ''}\`` : ''}`;
    const later = r.migs.slice(1).map((m) => fileLink(page, m.file, m.name));
    const owner = model.migrationOwner.get(first.file) ?? '';
    out.push(
      `| ${nameCell} | ${r.kind} | ${fileLink(page, first.file, first.name)} | ${later.length === 0 ? '' : later.join(', ')} | [${owner}](../code-map.md#${owner}) |`,
    );
  }
  return `${out.join('\n')}\n`;
}

export function renderControlMap(model: Model): string {
  const page = CONTROL_MAP;
  const out: string[] = ['# Control-to-code map', '', header(page), ''];
  out.push(
    'Each control of the register ([compliance/controls/](../../../compliance/controls/)) with the code that carries it',
    'and the test files that prove it, as the register records them. The tests carry the control ID in their names, for',
    'example `[DI-01]`. Modules are the [code map](../code-map.md) modules whose files the control names.',
    '',
  );
  const byStatus = new Map<string, number>();
  for (const c of model.controls) byStatus.set(c.buildStatus, (byStatus.get(c.buildStatus) ?? 0) + 1);
  out.push(
    `${model.controls.length} controls: ${[...byStatus.entries()]
      .sort((a, b) => compare(a[0], b[0]))
      .map(([s, n]) => `${n} ${s === '' ? 'without status' : s}`)
      .join(', ')}.`,
    '',
  );
  const moduleOf = new Map<string, string[]>();
  for (const m of model.modules) for (const c of m.controls) moduleOf.set(c.id, [...(moduleOf.get(c.id) ?? []), m.def.id]);
  for (const c of [...model.controls].sort((a, b) => compareControlIds(a.id, b.id))) {
    out.push(`## ${c.id}`, '');
    out.push(
      `**${esc(c.title)}.** [${c.id}.yaml](${relLink(page, c.file)}). Target phase ${c.targetPhase || 'none'}; editions ${list(c.editions)}; ${c.buildStatus || 'no status'}.`,
      '',
    );
    const mods = moduleOf.get(c.id) ?? [];
    if (mods.length > 0) out.push(`- Modules: ${mods.map((id) => `[${id}](../code-map.md#${id})`).join(', ')}`);
    for (const text of c.moduleTexts) out.push(`- Code: ${linkPaths(model, page, text)}`);
    for (const g of c.guards) out.push(`- Guard: ${esc(g)}`);
    if (c.testFiles.length > 0) out.push(`- Tests: ${c.testFiles.map((t) => (fileSet(model).has(t) ? fileLink(page, t, t) : `\`${t}\``)).join(', ')}`);
    if (mods.length === 0 && c.moduleTexts.length === 0 && c.guards.length === 0 && c.testFiles.length === 0) out.push('- Not implemented yet.');
    out.push('');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

/** An implemented_by entry with each existing repository path turned into a link. */
function linkPaths(model: Model, page: string, text: string): string {
  const safe = esc(text);
  return safe.replace(/(?:packages|apps|tools|compliance|docs|ops)\/[\w.\-/]*[\w-]/g, (p) => {
    const exists = fileSet(model).has(p) || dirSet(model).has(p);
    return exists ? `[${p}](${relLink(page, p)})` : `\`${p}\``;
  });
}

const sets = new WeakMap<Model, { files: Set<string>; dirs: Set<string> }>();
function index(model: Model): { files: Set<string>; dirs: Set<string> } {
  let s = sets.get(model);
  if (!s) {
    const dirs = new Set<string>();
    for (const f of model.files) for (let d = posix.dirname(f); d !== '.'; d = posix.dirname(d)) dirs.add(d);
    s = { files: new Set(model.files), dirs };
    sets.set(model, s);
  }
  return s;
}
function fileSet(model: Model): Set<string> {
  return index(model).files;
}
function dirSet(model: Model): Set<string> {
  return index(model).dirs;
}

export function renderErrorCodes(model: Model): string {
  const page = ERROR_CODES;
  const codes = errorCodes(model.root, model.files);
  const out: string[] = ['# Error codes', '', header(page), ''];
  out.push(
    'Every `EBMR-<AREA>-<NUMBER>` code named in the SQL migrations and the TypeScript source (tests excluded), with the',
    'files that raise, define or pass it on. To find where a code is raised, open the files and search for the code.',
    '',
    `${codes.size} codes.`,
    '',
    '| Code | Files |',
    '|---|---|',
  );
  for (const [code, files] of codes) out.push(`| \`${code}\` | ${files.map((f) => fileLink(page, f, f)).join(', ')} |`);
  return `${out.join('\n')}\n`;
}

export function renderAll(model: Model): Map<string, string> {
  return new Map([
    [CODE_MAP, renderCodeMap(model)],
    [DB_CATALOGUE, renderDbCatalogue(model)],
    [CONTROL_MAP, renderControlMap(model)],
    [ERROR_CODES, renderErrorCodes(model)],
  ]);
}
